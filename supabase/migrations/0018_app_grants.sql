-- 0018_app_grants.sql
-- ИНВАРИАНТ 15: ни одна функция схемы app не вызывается кем попало.
--
-- Эту дыру нашли мутационные тесты, и нашли не прямо: мутация «дать роли
-- сборщика право на очистку» выжила — тесты не покраснели. Выяснилось, что
-- право у сборщика и так было. И не только у него.
--
-- Откуда: в 0013 стоит
--
--     revoke execute on all functions in schema app from public;
--
-- и это сработало — но только для функций, которые существовали в тот момент.
-- `all functions` в Postgres означает «все, какие есть сейчас», а не правило
-- на будущее. Каждая следующая миграция создавала функции заново с правом
-- EXECUTE у PUBLIC, которое Postgres даёт по умолчанию.
--
-- К чему это привело. Роль anon — это посетитель каталога, у него нет ни
-- входа, ни агента. На момент этой миграции он мог вызвать:
--
--   app.upsert_candidate()     — вписать что угодно в пул кандидатов;
--   app.mark_candidates_gone() — объявить все объявления исчезнувшими;
--   app.release_stale_claims() — снять закрепления с работы агентов;
--   app.purge_candidates()     — удалить кандидатов вместе с журналом.
--
-- Все четыре — security definer, то есть выполняются с правами владельца, и
-- RLS их не останавливает. Тесты при этом были зелёными: они проверяли, что
-- нужным роли права есть, и ни один не проверял, что лишних прав нет.
--
-- Поэтому здесь не только разовая уборка, но и правило, которое видно
-- тестом: PUBLIC не вызывает ничего в схеме app. Права перечислены явно,
-- по роли, и следующая миграция, которая снова оставит функцию открытой,
-- провалит инвариант 15, а не доедет до боя.

-- ---------------------------------------------------------------------------
-- Разовая уборка: отнять у PUBLIC всё, выдать по роли нужное
-- ---------------------------------------------------------------------------

revoke execute on all functions in schema app from public;

-- Агент в кабинете. Полный набор: кто он — решает RLS и сами функции,
-- а не право вызова.
grant execute on all functions in schema app to authenticated;

-- Посетитель каталога. Ровно две функции, обе из 0013: отчёт собственника
-- по ссылке и определение агента, без которого каталог не читается.
grant execute on function app.owner_report(text)    to anon;
grant execute on function app.current_agent_id()    to anon;

-- Сборщик объявлений. Его контракт описан в collector/README.md: две функции
-- и ничего больше. Очистка в этот список не входит — удаление данных не дело
-- службы, которая ходит по чужим сайтам.
grant execute on function app.upsert_candidate(jsonb)                        to collector;
grant execute on function app.mark_candidates_gone(listing_source, text[], interval) to collector;

-- Отдельных revoke для сборщика здесь нет, и это не забывчивость. Лишнее
-- право у него было ровно одно — унаследованное от PUBLIC, и его отнимает
-- revoke выше. Своих грантов, кроме двух перечисленных, у роли нет. Строки
-- вида «revoke ... from collector» стояли здесь в первой версии; мутационный
-- тест показал, что их удаление ничего не меняет, то есть они ничего и не
-- делали. Мёртвая строка в правах хуже отсутствующей: она создаёт
-- впечатление, что что-то защищено именно ею.

-- ---------------------------------------------------------------------------
-- Правило на будущее
-- ---------------------------------------------------------------------------
-- Умолчание менять не станем: `alter default privileges` действует на роль,
-- которая создаёт объект, и в Supabase это не всегда тот, кого мы знаем.
-- Вместо умолчания — проверка, которую легко вызвать и которая висит в
-- тестах. Миграция, забывшая про права, упадёт на инварианте 15.

create or replace function app.functions_open_to_public()
  returns table (schema_name text, function_name text, is_definer boolean)
  language sql stable security definer set search_path = public, pg_temp as $$
  select n.nspname::text, p.proname::text, p.prosecdef
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'app'
     -- Пустой грантополучатель в ACL — это и есть PUBLIC. Пустой proacl
     -- означает умолчание, то есть тоже PUBLIC.
     and (p.proacl is null or array_to_string(p.proacl, ' ') like '=%')
   order by p.proname
$$;

comment on function app.functions_open_to_public is
  'Инвариант 15. Функции схемы app, доступные PUBLIC. Непустой результат — ошибка в правах, а не отчёт.';

-- Первым, кого нашла эта проверка, была она сама: функция создана после
-- revoke выше и получила умолчание PUBLIC. Так и должно быть — проверка,
-- которая не видит собственной ошибки, не видит и чужой.
revoke execute on function app.functions_open_to_public() from public;
grant  execute on function app.functions_open_to_public() to authenticated;
