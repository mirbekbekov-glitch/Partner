// Разбивает текст миграции на отдельные операторы.
//
// ЗАЧЕМ. Миграции опираются на пооператорную фиксацию: `psql -f` выполняет
// каждый оператор своей транзакцией, и 0039 этим пользуется — добавляет
// значение в перечисление, а ниже в том же файле его использует. Postgres
// запрещает использовать новое значение перечисления до фиксации добавившей
// его транзакции, поэтому файл, посланный одной транзакцией, падает с
// «unsafe use of new value». Так и случилось при первом прогоне по
// размещённому проекту.
//
// Разбивать по `;` наивно нельзя: миграции почти целиком состоят из тел
// функций в долларовых кавычках, где точек с запятой десятки. Поэтому здесь
// настоящий разбор — тот минимум лексики Postgres, который влияет на то, где
// кончается оператор.
//
// Проверка этого файла — не на глаз: `db/check-split.sh` прогоняет все
// миграции пооператорно в пустую базу и сверяет получившуюся схему с той,
// которую даёт db/rebuild.sh. Совпали — разбор верен.

/**
 * @param {string} text текст миграции
 * @returns {string[]} операторы без завершающей точки с запятой, пустые отброшены
 */
export function split(text) {
  const out = [];
  let start = 0;
  let i = 0;
  const n = text.length;

  while (i < n) {
    const c = text[i];

    // Строчный комментарий: до конца строки.
    if (c === "-" && text[i + 1] === "-") {
      while (i < n && text[i] !== "\n") i += 1;
      continue;
    }

    // Блочный комментарий. В Postgres они ВЛОЖЕННЫЕ, поэтому считается
    // глубина, а не ищется первый `*/`.
    if (c === "/" && text[i + 1] === "*") {
      let depth = 1;
      i += 2;
      while (i < n && depth > 0) {
        if (text[i] === "/" && text[i + 1] === "*") {
          depth += 1;
          i += 2;
        } else if (text[i] === "*" && text[i + 1] === "/") {
          depth -= 1;
          i += 2;
        } else {
          i += 1;
        }
      }
      continue;
    }

    // Строка в одинарных кавычках. Удвоенная кавычка внутри — это кавычка, а
    // не конец строки.
    if (c === "'") {
      i += 1;
      while (i < n) {
        if (text[i] === "'") {
          if (text[i + 1] === "'") {
            i += 2;
            continue;
          }
          i += 1;
          break;
        }
        i += 1;
      }
      continue;
    }

    // Имя в двойных кавычках — по тем же правилам.
    if (c === '"') {
      i += 1;
      while (i < n) {
        if (text[i] === '"') {
          if (text[i + 1] === '"') {
            i += 2;
            continue;
          }
          i += 1;
          break;
        }
        i += 1;
      }
      continue;
    }

    // Долларовые кавычки: $$ … $$ или $tag$ … $tag$. Метка — буквы, цифры и
    // подчёркивания, не начинающаяся с цифры. Важно не спутать с $1 из
    // параметров запроса: там после $ цифра, и это НЕ начало кавычек.
    if (c === "$") {
      const tag = dollarTag(text, i);
      if (tag) {
        const end = text.indexOf(tag, i + tag.length);
        // Незакрытые кавычки — это испорченный файл; дальше его читать
        // бессмысленно, и молчать об этом нельзя.
        if (end === -1) {
          throw new Error(`незакрытые долларовые кавычки ${tag} на позиции ${i}`);
        }
        i = end + tag.length;
        continue;
      }
    }

    if (c === ";") {
      const piece = text.slice(start, i).trim();
      if (piece) out.push(piece);
      i += 1;
      start = i;
      continue;
    }

    i += 1;
  }

  const tail = text.slice(start).trim();
  if (tail) out.push(tail);
  return out;
}

/**
 * Если в позиции `i` начинаются долларовые кавычки — вернуть их метку
 * целиком (`$$` или `$tag$`), иначе `null`.
 */
function dollarTag(text, i) {
  if (text[i] !== "$") return null;
  let j = i + 1;
  while (j < text.length) {
    const ch = text[j];
    if (ch === "$") return text.slice(i, j + 1);
    const ok =
      (ch >= "a" && ch <= "z") ||
      (ch >= "A" && ch <= "Z") ||
      ch === "_" ||
      // Цифра допустима в метке, но не первой: $1 — это параметр.
      ((ch >= "0" && ch <= "9") && j > i + 1);
    if (!ok) return null;
    j += 1;
  }
  return null;
}
