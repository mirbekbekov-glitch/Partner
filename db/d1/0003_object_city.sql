-- Город объекта.
--
-- Раньше города не было вовсе: подразумевался Бишкек, и в выгрузку на
-- площадки он подставлялся из константы. Это держалось ровно до первого
-- объекта в другом городе — и тот молча уехал бы в Бишкек.
--
-- Значение по умолчанию «Бишкек» не догадка: на момент этой правки все
-- объекты бишкекские (их ноль), а новые без явного города — тоже оттуда.
alter table objects add column city text not null default 'Бишкек';

create index if not exists objects_city_idx on objects (city);
