-- Что именно ищет человек: словарь вместо семи ведёр.
--
-- Зачем. В заявке было семь значений, и «коммерческая» означала сразу
-- офис, кабинет, здание, склад и торговую точку. Рабочего места не было
-- вовсе. Человек, который ищет кабинет на двоих, не находил себя в списке
-- и писал «другое» — а агент потом звонил выяснять то, что можно было
-- спросить формой.
--
-- Почему НОВАЯ колонка, а не правка старой. У housing_type стоит CHECK со
-- списком значений, а менять CHECK в SQLite нельзя — только перестройкой
-- таблицы целиком. Перестраивать живую таблицу заявок ради словаря
-- несоразмерно риску.
--
-- Старая колонка остаётся и продолжает заполняться огрублённым значением:
-- на неё опираются порог рынка, подбор и превращение заявки в
-- потребность. Новая колонка — то, что человек выбрал на самом деле, и
-- это видит агент.
alter table requests add column space_type text
  check (space_type is null or space_type in (
    -- Жильё
    'flat', 'room', 'house', 'townhouse', 'land', 'garage',
    -- Коммерция
    'office', 'cabinet', 'building', 'retail', 'warehouse', 'production',
    -- Рабочее место
    'desk'
  ));

-- Срок аренды: от скольки до скольки.
--
-- Зачем. «Сниму квартиру» значит разное: посуточно на выходные, на три
-- месяца под командировку и на год с семьёй — это три разных объекта и
-- три разные цены. Сейчас срок не спрашивался вовсе, и агент выяснял его
-- звонком, то есть терял первый разговор на то, что форма могла узнать
-- сама.
--
-- В ДНЯХ, а не в месяцах и не признаком «короткий/долгий». Месяцы не
-- выражают посуточную аренду, а признак не выражает ни «на две недели»,
-- ни «от года». Дни выражают всё, и пресеты в форме («посуточно»,
-- «до месяца», «от года») — это подпись к числам, а не второй источник
-- правды.
--
-- Только для аренды. У покупки срока нет, и форма поле прячет.
alter table requests add column term_days_min integer
  check (term_days_min is null or term_days_min > 0);
alter table requests add column term_days_max integer
  check (term_days_max is null or term_days_max > 0);
