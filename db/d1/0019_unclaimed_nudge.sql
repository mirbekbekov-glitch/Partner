-- Отметка о том, что про непринятую заявку уже написали.
--
-- Зачем отдельная колонка, а не idle_notified_at. Это разные события в
-- разные моменты жизни заявки: «никто не взял» бывает ДО взятия,
-- «взяли и ничего не нашли» — после. Одна колонка на оба означала бы, что
-- первое напоминание глушит второе, и заявка, про которую написали в
-- десять утра, уже не напомнит о себе через сутки.
alter table requests add column unclaimed_notified_at text;

create index if not exists requests_new_idx
  on requests (status, created_at) where status = 'new';
