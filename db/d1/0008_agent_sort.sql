-- Сопоставимый вид имени агента: для порядка в списках.
--
-- Зачем. SQLite сравнивает строки побайтно, и для кириллицы это значит,
-- что все заглавные идут перед всеми строчными: «Абрамов, Орозов,
-- Яковлев, абрамов, яковлев» — проверено запросом к боевой базе. Колонка
-- «ведёт» в списках объектов и потребностей сортировалась по full_name,
-- то есть агент, записанный строчными, уезжал в конец.
--
-- Почему колонкой, хотя у контактов для поиска дубликатов решение было
-- обратным. Там правило (инициалы) на SQL не выражается вовсе, а здесь
-- нужен именно SQL: списки постраничные, и порядок обязан стоять в
-- запросе — иначе переставлялась бы только загруженная страница.
--
-- Цена честно названа: имя агента пишется в ТРЁХ местах (заведение,
-- переименование при входе, правка профиля), и колонку надо обновлять в
-- каждом. Риск расхождения закрыт тремя проверками, по одной на путь, —
-- каждая падает, если своё место забыли.
alter table agents add column name_sort text not null default '';

create index if not exists agents_name_sort_idx on agents (name_sort);
