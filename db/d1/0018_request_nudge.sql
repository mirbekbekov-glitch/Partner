-- Отметка о том, что по заявке агенту уже напомнили.
--
-- Зачем колонка, а не запись в очереди напоминаний. Очередь
-- (notifications) жёстко привязана к активности: activity_id там NOT NULL
-- и ссылается на activities. Заявка активностью не является, и чтобы
-- положить её в ту же очередь, пришлось бы перестраивать таблицу целиком
-- — SQLite не умеет снимать NOT NULL на месте. Перестройка живой таблицы
-- ради одного поля несоразмерна риску.
--
-- Идемпотентность даёт сама колонка: напоминание уходит, когда она
-- пустая, и заполняется тем же прогоном. Повторный прогон расписания
-- ничего не продублирует — то же свойство, что у unique в очереди, но без
-- перестройки.
--
-- Колонка хранит ВРЕМЯ, а не признак: по нему видно, когда напомнили, и
-- можно будет напомнить второй раз через неделю, не меняя схему.
alter table requests add column idle_notified_at text;

create index if not exists requests_idle_idx
  on requests (status, taken_at) where status = 'in_work';
