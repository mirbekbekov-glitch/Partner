-- Курс Нацбанка: один источник правды для пересчёта цен.
--
-- Зачем таблица, а не переменная окружения. Курс меняется каждый день, а
-- переменные задаются при выкладке: курс в переменной означал бы выкладку
-- ради числа. Плюс рядом с курсом обязана стоять ДАТА, на которую он
-- взят, — без неё пересчёт нечестен: человек вправе знать, насколько
-- свежее то, что ему показали.
--
-- Ключ — код валюты, хотя пока нужен только доллар: так EUR и прочие
-- добавятся записью, а не изменением схемы.
--
-- som_per_unit — сколько сомов за ОДНУ единицу. Нацбанк отдаёт значение
-- на Nominal единиц, и деление делает код при разборе, а не читатель.
create table if not exists fx_rates (
  code         text primary key check (length(code) = 3),
  som_per_unit real not null check (som_per_unit > 0),
  -- Дата, на которую курс объявлен Нацбанком.
  as_of        text not null,
  -- Когда мы его забрали: расходится с as_of в выходные и праздники,
  -- и по этой паре видно, работает ли подтягивание вообще.
  fetched_at   text not null
);
