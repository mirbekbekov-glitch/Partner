-- Панорамы для 3D-тура.
--
-- Отдельной колонкой от photos, а не вместе с ними: это разные вещи.
-- Снимок показывают в ленте и в обложке, панораму нельзя показать как
-- снимок — она выглядит растянутой полосой. Смешай их в одном списке, и
-- обложкой объявления однажды станет кривая панорама.
--
-- Хранится JSON-массив: [{key, url, room, w, h}]. Ширина и высота нужны
-- просмотрщику: по их отношению он понимает, сколько градусов по
-- вертикали охватывает снимок. Считаются они в браузере при загрузке —
-- в Worker'е картинку разобрать нечем.
--
-- Почему JSON, а не отдельная таблица: панорам у объекта единицы, они
-- всегда читаются вместе с объектом и никогда — отдельно. Таблица дала
-- бы соединение в каждом запросе витрины ради десятка строк на всю базу.
