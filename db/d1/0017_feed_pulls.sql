-- Кто и когда забирал фид.
--
-- ЗАЧЕМ. Кабинет до сих пор не знал, опубликован ли объект на площадке, —
-- и ответить на вопрос «наше объявление уже на house.kg?» можно было
-- только сходив туда руками. Таблица publication_channels для этого и
-- заведена, но писал в неё НИКТО: отметки только снимались при снятии с
-- публикации и при расторжении мандата.
--
-- ЧТО ЭТО ДОКАЗЫВАЕТ, А ЧТО НЕТ. Две разные вещи, и путать их нельзя:
--
--   «объект попал в выгрузку» — наш факт, мы его знаем точно;
--   «площадка забрала фид»    — тоже наш факт: запрос пришёл к нам;
--   «объявление опубликовано» — НЕ НАШ факт. Его знает только площадка,
--                               и пока она не сообщает нам ничего,
--                               утверждать это нельзя.
--
-- Поэтому на карточке объекта будет написано ровно первое и второе, а не
-- третье. Соблазн написать «опубликовано на house.kg» велик, но это было
-- бы обещание за чужой счёт.

create table if not exists feed_pulls (
  -- Один фид — одна строка. Накопительной истории здесь нет сознательно:
  -- фид открыт всем, и каждый запрос поисковика или любопытного добавлял
  -- бы строку. Нужен последний раз, а не журнал.
  channel    text primary key check (channel in ('house_kg', 'yandex')),
  last_at    text not null,
  -- Чем представился тот, кто забирал. Нужен, чтобы отличить площадку от
  -- поискового робота и от нас самих.
  last_agent text,
  -- Сколько раз забирали всего. Растёт не на каждый запрос, а не чаще
  -- одного раза в десять минут — см. lib/db/feed-log.ts.
  pulls      integer not null default 0
);
