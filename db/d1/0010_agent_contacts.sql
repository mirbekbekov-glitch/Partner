-- Связь с агентом прямо из объявления.
--
-- До сих пор телефон агента наружу не показывался: звонок шёл в отдел
-- продаж, чтобы объект не уводили мимо агентства. Решение изменено
-- владельцем площадки: покупатель пишет тому, кто ведёт объект.
--
-- Мессенджеры заводятся ОТДЕЛЬНЫМИ полями, а не угадываются по номеру.
-- Проверить, есть ли на номере WhatsApp или Telegram, нельзя: ни один из
-- них такого не отдаёт. Кнопка, ведущая в пустоту, хуже отсутствия
-- кнопки — покупатель решит, что агент не отвечает.
alter table agents add column whatsapp integer not null default 0
  check (whatsapp in (0, 1));

-- Ник, а не номер. Ссылка t.me по номеру работает только у тех, кто
-- разрешил искать себя по телефону, и молча не работает у остальных.
alter table agents add column telegram_user text;
