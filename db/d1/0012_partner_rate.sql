-- Комиссия партнёру — процент ОТ СДЕЛКИ, а не доля нашей комиссии.
--
-- Вчерашняя колонка partner_share оказалась не тем, что называет агент.
-- Агент говорит так, как говорят на рынке: «отдаю 1 % при продаже»,
-- «половину месяца при аренде». Это процент от цены (при аренде — от
-- месячной платы), и он не зависит от того, сколько берёт с объекта
-- сам ведущий агент.
--
-- Дробный процент обязателен: 0,5 % при продаже — обычное условие, а в
-- целых процентах его не записать. Поэтому real, а не integer.
--
-- partner_share остаётся в таблице и больше не читается: сносить колонку
-- в SQLite значит пересобирать таблицу, а пустая колонка никому не
-- мешает. Пусто в partner_rate — прежнее правило: половина комиссии.
alter table mandates add column partner_rate real
  check (partner_rate is null or (partner_rate >= 0 and partner_rate <= 100));
