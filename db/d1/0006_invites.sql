-- Приглашение агента ссылкой, которую передаёт админ.
--
-- Зачем. Вход устроен письмом со ссылкой, но на бесплатном плане Workers
-- письмо уходит ТОЛЬКО на заранее подтверждённый адрес, а адрес нового
-- агента никто заранее не подтверждал. Значит до сих пор завести второго
-- человека было нельзя вовсе: форма входа отвечает «письмо отправлено», и
-- письмо не приходит. Агентство заводит людей через WhatsApp, и ссылка
-- пойдёт тем же путём — её выдаёт админ в кабинете и передаёт сам.
--
-- Отдельной таблицы нет намеренно: приглашение — это тот же одноразовый
-- токен входа, и гасить его должен ТОТ ЖЕ запрос, что гасит обычную
-- ссылку. Две таблицы означали бы две проверки одноразовости, и вторая
-- однажды отстала бы от первой.
--
-- Кто выдал. Обычный вход никто не выдаёт, там пусто. У приглашения стоит
-- админ: ссылка даёт вход в чужую учётную запись, и такое не должно
-- случаться анонимно. Удаление админа запись о выдаче не стирает —
-- on delete set null, а не cascade: уволившийся админ не повод терять
-- след того, кого он завёл.
alter table login_tokens add column issued_by_agent_id text
  references agents (id) on delete set null;

create index if not exists login_tokens_issued_idx
  on login_tokens (issued_by_agent_id) where issued_by_agent_id is not null;
