-- Дата публикации объявления и его координаты.
--
-- Отдельной миграцией, а не правкой 0015: на базе, где таблицы уже есть,
-- `create table if not exists` — пустая операция, и дописанная туда
-- колонка до боевой базы не доедет. Это правило стоило упавшей выкладки
-- 26 ноября 2026 года, подробности в README.
--
-- ЗАЧЕМ ДАТА. В выдаче поиска её нет: там «4 часа назад», и это когда
-- объявление ПОДНЯЛИ, а не когда подали. Разница решающая для поиска
-- собственников: поднятое сегодня объявление может висеть с весны, и
-- именно такой продавец устал продавать сам.
--
-- Заполняется не обходом выдачи, а отдельным проходом по страницам самих
-- объявлений — и только у тех, кто похож на собственника. Ходить за
-- датой для каждого объявления значило бы сорокакратный трафик ради
-- поля, которое нужно сотне строк из тысячи.
alter table market_listings add column posted_at text;

-- Координаты берутся тем же проходом, раз уж страница всё равно
-- прочитана. Сейчас ими никто не пользуется; понадобятся карте.
alter table market_listings add column latitude  real;
alter table market_listings add column longitude real;

-- Выборка «кому ещё не знаем дату»: только собственники, только живые.
create index if not exists market_listings_posted
  on market_listings (seller_kind, posted_at, gone_at);
