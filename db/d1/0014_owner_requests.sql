-- Заявка собственника: «сдам или продам», а не только «ищу».
--
-- До сих пор заявку можно было оставить лишь на поиск: deal принимает
-- 'buy' и 'rent', то есть описывает спрос. Человеку с квартирой на руках
-- на сайте было некуда нажать — он либо звонил, либо уходил. Путь, которым
-- приходит товар, был длиннее пути, которым приходит покупатель.
--
-- Сторона заявки не заводится отдельной колонкой: она выводится из
-- offer_deal. Заполнено — заявка от собственника, пусто — обычный поиск.
-- Отдельный флаг рядом с ним пришлось бы держать в согласии руками, и
-- однажды они разошлись бы.
--
-- Значения те же, что у объекта (objects.deal_type), а не 'sell'/'let':
-- заявка собственника — заготовка объекта, и переводить одно в другое при
-- заведении карточки незачем.
--
-- Колонка добавляется, а не меняется существующая: проверку deal пришлось
-- бы пересобирать таблицей целиком, а схема накатывается при КАЖДОЙ
-- выкладке — перестройка выполнялась бы каждый раз.
alter table requests add column offer_deal text
  check (offer_deal is null or offer_deal in ('sale', 'rent'));

-- Адрес объекта, который предлагают. У заявки на поиск его нет и быть не
-- может: ищут район, а не дом. Район остаётся в district_id — он общий
-- для обеих сторон и ведётся справочником.
alter table requests add column address text
  check (address is null or length(trim(address)) <= 200);

-- Лента кабинета открывается на свободных заявках и делится по стороне:
-- собственник и покупатель — разная работа, и смотрят их разные агенты.
create index if not exists requests_offer_idx on requests (offer_deal, created_at);
