-- Доля партнёра: сколько от комиссии получит агент, который приведёт
-- покупателя.
--
-- До сих пор доля была ЗАШИТА в коде: ровно половина, всегда. Для
-- площадки, которая живёт сотрудничеством агентов, это главное условие
-- сделки, и оно не может быть константой: один отдаёт половину, другой
-- треть, третий — процент от цены сверх своей комиссии. Пока условие
-- нельзя было назвать, агенты договаривались о нём вне площадки, и
-- площадка о нём не знала.
--
-- Процент от комиссии, а не сумма: сумма устареет при первой же смене
-- цены, а доля переживёт и смену цены, и смену правила комиссии.
--
-- Пусто — прежнее правило: половина. Так объекты, заведённые до этой
-- колонки, не меняют смысла.
alter table mandates add column partner_share integer
  check (partner_share is null or (partner_share between 0 and 100));
