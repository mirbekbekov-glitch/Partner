-- Карточка агента: лицо, стаж, сертификат.
--
-- Зачем. Объявление ведёт человек, и покупатель решает не только по
-- квартире, но и по тому, с кем ему разговаривать. До сих пор про агента
-- не было известно ничего, кроме имени.
--
-- Стаж хранится ГОДОМ НАЧАЛА, а не числом лет. «5 лет», записанное
-- сегодня, через два года станет неправдой, и поправить это никто не
-- вспомнит. Год начала не протухает: число лет считается при показе.
alter table agents add column works_since integer;

-- Номер в реестре риэлторов. Подтверждение — отдельным полем, как у
-- агентства: агент ЗАЯВЛЯЕТ, админ сверяет. Иначе любой впишет чужой
-- номер и прикроется им перед клиентом.
alter table agents add column certificate_no text;
alter table agents add column certificate_confirmed integer not null default 0;

-- Ключ снимка в R2. Полного адреса здесь нет намеренно — тот же довод,
-- что и у снимков объектов: сменится хранилище или домен, и все ссылки
-- разом станут битыми.
alter table agents add column avatar_key text;
