-- Срок аренды объекта в днях: посуточно отдельно от «снять».
--
-- Зачем. Срок у объекта был, но словами справочника площадки —
-- «посуточно», «помесячно», «на долгий срок». Отбирать по ним нельзя:
-- это чужой словарь, он живёт по чужим правилам, и «посуточно» в нём не
-- отличается от «по часам» ничем, кроме написания. А посуточная аренда —
-- отдельный способ пользоваться площадкой: так сдают квартиры, хостелы и
-- рабочие места в коворкинге.
--
-- В днях, потому что в днях уже лежит срок в заявках (0020). Одна
-- единица на обе стороны — единственный способ однажды свести заявку с
-- объектом: «ищу на три дня» против «сдаётся от месяца».
--
-- Значение для справочника площадки ВЫВОДИТСЯ отсюда при выгрузке, как и
-- вид коммерции (0021). Прежняя колонка rental_term остаётся запасным
-- путём для объектов, заведённых раньше.
alter table objects add column term_days_min integer;
alter table objects add column term_days_max integer;

-- Отбор «посуточно» идёт по нижней границе, и без индекса он читал бы
-- всю таблицу на каждый заход в этот раздел.
create index if not exists objects_term_idx on objects (term_days_min)
  where term_days_min is not null;
