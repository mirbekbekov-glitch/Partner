-- Точный вид объекта: кабинет отдельно от офиса, коворкинг отдельно от обоих.
--
-- Зачем. В objects.kind семь значений, и всё нежилое — одно ведро
-- «commercial». Подписывать карточку точнее удавалось через
-- commercial_type, но это словарь ПЛОЩАДКИ, и кабинета с рабочим местом
-- в коворкинге в нём нет. А это настоящий товар, а не редкий случай.
--
-- Почему колонка, а не правка kind. CHECK в SQLite меняется только
-- перестройкой таблицы, а на objects ссылаются мандаты, подборы, сделки
-- и связи собственности. Перестройка такой таблицы ради словаря —
-- несоразмерный риск.
--
-- kind остаётся и продолжает работать: на нём держатся публикация,
-- выгрузка в фид, фильтр каталога и порог рынка. subkind — уточнение,
-- ВСЕГДА согласованное с ним: код проверяет, что точный вид огрубляется
-- именно в тот kind, который стоит у объекта.
--
-- Список шире списка заявок (0020) на семь значений: справочник площадки
-- различает общепит, отель, автосервис, салон красоты, медцентр,
-- сельхозугодье и торговый контейнер, и будь наш словарь беднее, выгрузка
-- потеряла бы точность. Значение для площадки теперь выводится отсюда, а
-- не спрашивается отдельно.
alter table objects add column subkind text
  check (subkind is null or subkind in (
    'flat', 'room', 'house', 'townhouse', 'land', 'garage',
    'office', 'cabinet', 'building', 'retail', 'warehouse', 'production',
    'desk',
    'catering', 'hotel', 'auto', 'beauty', 'medical', 'agriculture',
    'container'
  ));

create index if not exists objects_subkind_idx on objects (subkind)
  where subkind is not null;
