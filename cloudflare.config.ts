/**
 * Worker: что он такое, по какому расписанию просыпается и что ему доступно.
 *
 * Здесь всё, что платформа даёт Worker'у: база, хранилище снимков, модель,
 * отправка писем, расписание и секреты.
 */
import { bindings, defineConfig, defineWorker, triggers } from 'cf/config';

export default defineConfig({
  worker: defineWorker({
    name: 'partner',

    // Своя точка входа, а не vinext/server/fetch-handler напрямую: у
    // платформы нет способа вызвать HTTP-маршрут по расписанию, нужен
    // scheduled(). Запросы посетителей worker/index.ts передаёт тому же
    // обработчику vinext, ничего не меняя.
    entrypoint: './worker/index.ts',

    compatibilityDate: '2026-11-22',

    // Node-совместимость нужна библиотекам Supabase и генератору карточки
    // превью: без неё Worker падает на отсутствующих модулях Node.
    compatibilityFlags: ['nodejs_compat'],

    assets: {
      htmlHandling: 'none',
      notFoundHandling: 'none',
      runWorkerFirst: ['/*', '!/_next/static/*', '!/*/_next/static/*'],
    },

    // Журналы. Без них рассылка по расписанию — чёрный ящик: сработала она
    // или нет, видно только по тому, пришли ли напоминания. Включено здесь,
    // а не в панели: выкладка идёт с --force и затёрла бы правку, сделанную
    // мимо кода.
    observability: { enabled: true },

    // Два расписания, и это не удобство, а необходимость.
    //
    // Суточное, 9:07 UTC (15:07 в Бишкеке): напоминания о задачах, курс
    // Нацбанка, перенос каталога, гашение мандатов, уборка сессий. Всё
    // это суточное по смыслу, а курс и перенос ещё и ходят наружу —
    // дёргать их каждые четверть часа значило бы молотить чужие сервера
    // без нужды.
    //
    // Частое, каждые 15 минут: непринятые заявки. «Заявку не взяли два
    // часа» при суточном прогоне превращается в «не взяли сутки», то есть
    // в бессмыслицу. Сюда попадает только то, что идемпотентно и дёшево:
    // один запрос в свою же базу.
    //
    // Какое расписание сработало, обработчик узнаёт по controller.cron.
    triggers: [
      triggers.scheduled({ schedule: '7 9 * * *' }),
      triggers.scheduled({ schedule: '*/15 * * * *' }),
    ],

    env: {
      ASSETS: bindings.assets(),

      // База. Заменяет Supabase целиком: таблицы, вход и журнал действий.
      //
      // Только имя: идентификатор необязателен, базу с таким именем
      // Cloudflare заводит сама при первой выкладке. Вписанный сюда
      // database_id привязал бы репозиторий к одному аккаунту.
      //
      // Привязка требует у токена выкладки прав D1:Edit — без них выкладка
      // падает на последнем шаге с «[10000] Authentication error». Один раз
      // это уже случилось; прод тогда уцелел, потому что падает шаг после
      // сборки, и прежний Worker остаётся на месте.
      DB: bindings.d1({ name: 'partner' }),

      // База снимка каталога старого сайта. Её наполняет ЧУЖОЙ Worker
      // (hidden-pine-cbff, маршрут /api/catalog-sync): старый сайт раз в
      // сутки присылает туда свой каталог, тот складывает его одной
      // строкой CSV. Нам она нужна только на чтение — расписание заводит
      // из неё черновики объектов (lib/db/catalog-import.ts). Писать в
      // неё мы не имеем права: там чужая запись, и спорить за неё двум
      // Worker'ам не из-за чего.
      CATALOG: bindings.d1({ name: 'liberterra-catalog' }),

      // Фотографии объектов. Раньше агент вставлял ссылку на чужой хостинг,
      // и ссылка протухала вместе с чужим хостингом: вместо снимка
      // рисовался фасад.
      //
      // Ведро заводится само по имени. R2 — отдельная услуга, и пока она на
      // аккаунте не включена, Cloudflare отвечает «10042: Please enable R2
      // through the Cloudflare Dashboard», а выкладка падает общим
      // «[10000] Authentication error, 401», по которому причину не угадать.
      PHOTOS: bindings.r2({ name: 'partner-photos' }),

      // Модель: черновик описания объекта (lib/ai/describe.ts).
      //
      // Привязки здесь НЕ БЫЛО, хотя код её звал. Выкладка от этого не
      // падала и тесты не краснели: describeObject() проверяет наличие
      // привязки и отвечает «Генерация не настроена», а не бросает
      // исключение. То есть кнопка на бою молча отказывала, и узнать об
      // этом можно было только нажав её.
      //
      // Это цена честной обработки отсутствующей привязки: она же прячет
      // то, что привязку забыли объявить. Лечится не кодом, а строкой
      // ниже — доступ к модели выдаёт площадка, ключа не существует.
      AI: bindings.ai(),

      // Отправка писем: ссылки для входа в кабинет.
      //
      // Через привязку, а не через внешний почтовик с ключом: это та же
      // мысль, что и с Workers AI — доступ выдаёт площадка, а не ключ в
      // секретах. Домен liberterra.kg заведён в Email Sending, записи DNS
      // настроены.
      //
      // Без ограничения адресатов: агенты входят со своих почт, и список
      // их адресов заранее неизвестен.
      EMAIL: bindings.sendEmail(),

      // Адрес отправителя. Не секрет — его видно в каждом письме, — поэтому
      // обычным значением, а не секретом: одной ручной настройкой меньше.
      MAIL_FROM: bindings.text('cabinet@liberterra.kg'),

      // Контакт агентства в выгрузке на площадки. Пусто — блок контакта
      // в фид не выводится вовсе: пустой телефон площадка примет за
      // настоящий, и по объявлению будут звонить в никуда.
      FEED_PHONE: bindings.text('+996 505 804 402, +996 500 804 402'),
      FEED_ORG: bindings.text('Liberterra'),

      // Имя бота для ссылки привязки. Не секрет: оно и так видно в чате.
      //
      // Здесь нужен АДРЕС бота (@username), а не отображаемое имя. У этого
      // бота они разные: адрес Libertrerra_Bot, а в заголовке чата
      // Telegram пишет «Liberterra_Bot». Я однажды принял второе за первое
      // и сломал привязку: ссылка повела на чужого бота, у которого нашего
      // обработчика нет. Проверять адрес надо по @BotFather или по самой
      // ссылке t.me/…, а не по шапке чата.
      TELEGRAM_BOT_USERNAME: bindings.text('Libertrerra_Bot'),

      // Собственный адрес сайта: нужен карте сайта и превью при пересылке.
      NEXT_PUBLIC_SITE_URL: bindings.secret(),

      // Секрет расписания. Маршрут рассылки ходит в базу без сессии агента,
      // то есть мимо проверок прав, поэтому закрыт секретом. Незаданный
      // секрет — ошибка настройки, и маршрут тогда отказывает, а не
      // открывается.
      CRON_SECRET: bindings.secret(),
      TELEGRAM_BOT_TOKEN: bindings.secret(),

      // TELEGRAM_WEBHOOK_SECRET здесь НАМЕРЕННО не объявлен, хотя маршрут
      // бота его читает.
      //
      // Объявленный секрет — это требование при выкладке: пока его не
      // задали на Worker, выкладка отказывается. Для одного маршрута это
      // слишком дорого — отказ останавливает выкладку всего сайта, в том
      // числе чужих правок, и однажды уже остановил.
      //
      // Защита от этого не пропадает: сам маршрут без секрета отвечает 503
      // и тела не читает. То есть незаданный секрет выключает привязку, а
      // не открывает её — а это и есть то, что требовалось.
      //
      // Цена решения названа честно: о незаданном секрете узнаёшь не при
      // выкладке, а когда привязка не работает. Записано в README.
    },
  }),
});
