'use client';

import { useEffect, useRef } from 'react';

/**
 * Фон героя: консольная лестница — ступени, висящие в воздухе.
 *
 * Лестница — мотив из знака агентства, где квадраты сложены ступенями.
 *
 * Почему именно консольная. Сплошной марш сбоку читался лестницей, но и
 * оставался плоской фигурой: силуэт без материала и без света. Здесь
 * каждая ступень — отдельная плита, у неё видны проступь и торец, она
 * отбрасывает мягкую тень на стену и ни на что не опирается снизу.
 * Промежутки между плитами не дают прочитать её ни пандусом, ни
 * диаграммой, а консоль — это прямая цитата из современной
 * архитектуры, а не геометрическая фигура.
 *
 * Глубина мелкая и одинаковая у всех плит: ровно столько, чтобы плита
 * стала плитой. Полная изометрия уже была и подводила — три грани и
 * ограждение дают узнаваемый предмет, но теряют направление.
 *
 * Свет сверху слева, как и на остальном первом экране: проступь светлая,
 * торец в тени, тень на стене уходит вправо и вниз. Тени размывает
 * фильтр, а не слой полупрозрачных копий: один проход на всю группу.
 *
 * Подъём показан, а не только нарисован: плиты встают снизу вверх, одна
 * за другой. Направление движения доходит раньше, чем человек разберёт
 * рисунок. Движение одноразовое, при «меньше движения» его нет вовсе.
 *
 * Собрана вектором, а не картинкой: режется на любом экране без мыла,
 * весит килобайты и перекрашивается вместе с темой.
 */
export function HeroArt() {
  const box = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = box.current;
    if (!el) return;
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    if (!window.matchMedia('(pointer: fine)').matches) return;

    let raf = 0;
    const onMove = (e: PointerEvent) => {
      if (raf) return;
      raf = requestAnimationFrame(() => {
        raf = 0;
        const r = el.getBoundingClientRect();
        const x = e.clientX - r.left;
        const y = e.clientY - r.top;
        el.style.setProperty('--mx', `${x}px`);
        el.style.setProperty('--my', `${y}px`);
        // Сдвиг в противоход курсору и в десять раз слабее: предмет
        // отзывается, но не убегает.
        el.style.setProperty('--px', `${(0.5 - x / r.width) * 18}px`);
        el.style.setProperty('--py', `${(0.5 - y / r.height) * 12}px`);
      });
    };
    const parent = el.parentElement ?? el;
    parent.addEventListener('pointermove', onMove);
    return () => {
      parent.removeEventListener('pointermove', onMove);
      if (raf) cancelAnimationFrame(raf);
    };
  }, []);

  return (
    <div className="hero-art" ref={box} aria-hidden="true">
      <div className="hero-glow" />
      <svg viewBox="0 0 560 470" preserveAspectRatio="xMidYMid meet">
        <defs>
          {/* Проступь: свет падает сверху слева, поэтому ближний край
              светлее дальнего. */}
          <linearGradient id="tread" x1="0" y1="1" x2="0.35" y2="0">
            <stop offset="0" stopColor="#E85A54" />
            <stop offset="1" stopColor="#C8332E" />
          </linearGradient>
          {/* Торец плиты — в тени: он и даёт плите толщину. */}
          <linearGradient id="nose" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0" stopColor="#B42621" />
            <stop offset="1" stopColor="#8B1A16" />
          </linearGradient>
          {/* Боковой срез: самая тёмная грань, видна справа. */}
          <linearGradient id="flank" x1="0" y1="0" x2="1" y2="0">
            <stop offset="0" stopColor="#9C201C" />
            <stop offset="1" stopColor="#6E1310" />
          </linearGradient>
          {/* Мягкая тень на стене. Размывается фильтром — один проход на
              всю группу теней, а не стопка полупрозрачных копий. */}
          <filter id="soft" x="-30%" y="-30%" width="180%" height="180%">
            <feGaussianBlur stdDeviation="9" />
          </filter>
        </defs>
        <Frame />
        <Flight />
      </svg>
    </div>
  );
}

/* Лестница ПОДНИМАЕТСЯ слева направо. Направление не декоративное:
   подъём читается как движение вверх, спуск — как вниз, и на первом
   экране агентства недвижимости нужен первый.

   Семь плит, а не три и не двенадцать: на трёх подъём не успевает стать
   подъёмом, на двенадцати плиты мельчают до штрихов. */
const N = 7;
const STEP_X = 46;  // смещение каждой следующей плиты вправо
const STEP_Y = 40;  // и вверх
const LEN = 104;    // длина плиты
const TH = 13;      // толщина
const DX = 30;      // глубина: вектор в правый верхний угол
const DY = -17;
const X0 = 54;
const Y0 = 392;

const pt = (x: number, y: number) => `${x.toFixed(1)},${y.toFixed(1)}`;

/** Одна плита: проступь, торец, боковой срез. */
function Slab({ x, y }: { x: number; y: number }) {
  return (
    <>
      {/* Проступь — верхняя грань, по ней идут. */}
      <polygon fill="url(#tread)" points={[
        pt(x, y), pt(x + LEN, y), pt(x + LEN + DX, y + DY), pt(x + DX, y + DY),
      ].join(' ')} />
      {/* Торец: передняя кромка. Без неё плита — плоский четырёхугольник. */}
      <polygon fill="url(#nose)" points={[
        pt(x, y), pt(x + LEN, y), pt(x + LEN, y + TH), pt(x, y + TH),
      ].join(' ')} />
      {/* Боковой срез уходит в глубину. */}
      <polygon fill="url(#flank)" points={[
        pt(x + LEN, y), pt(x + LEN + DX, y + DY),
        pt(x + LEN + DX, y + DY + TH), pt(x + LEN, y + TH),
      ].join(' ')} />
    </>
  );
}

function Flight() {
  const slabs: React.ReactElement[] = [];

  // От нижней плиты к верхней: верхняя перекрывает нижнюю, и порядок
  // отрисовки заменяет расчёт видимости.
  for (let i = 0; i < N; i++) {
    const x = X0 + i * STEP_X;
    const y = Y0 - i * STEP_Y;
    slabs.push(
      <g key={i} className="slab" style={{ animationDelay: `${i * 70}ms` }}>
        {/* Тень этой плиты на стене позади. Своя у каждой — иначе она
            не сдвинулась бы вместе с плитой при появлении.

            Падает ПОД плиту, а не вбок: свет сверху, и тень, уехавшая
            вправо от плиты, читалась не тенью, а серым пятном рядом.
            Повторяет форму самой плиты сверху, поэтому и выглядит её
            тенью, а не прямоугольником. */}
        <g filter="url(#soft)">
          <polygon fill="var(--art-ink)" opacity=".17" points={[
            pt(x + 10, y + TH + 14), pt(x + LEN + 10, y + TH + 14),
            pt(x + LEN + DX + 10, y + DY + TH + 14), pt(x + DX + 10, y + DY + TH + 14),
          ].join(' ')} />
        </g>
        <Slab x={x} y={y} />
      </g>,
    );
  }

  return <>{slabs}</>;
}

/**
 * Каркас: линии построения вокруг лестницы.
 *
 * Чертёж, а не украшение: короткие отметки проступей за дальним краем
 * плит. Так рисуют конструкцию до того, как её построят, — и это ровно
 * то, чем занимается агентство: показывает пространство, которого
 * человек ещё не видел.
 *
 * Ни вертикали «стены», ни выносного размера здесь нет намеренно. Стены
 * на рисунке не нарисовано, и линия у первой плиты читалась случайной
 * чертой; выносной размер остался от сплошного марша и у консолей висел
 * сам по себе, ни к чему не привязанный.
 *
 * Горизонтальных линий уровня здесь намеренно нет: шесть линий поперёк
 * рисунка превращают любые ступени в диаграмму роста.
 *
 * Линии тонкие и серые, и они уходят ПОД красный объём: на чертеже
 * готовая деталь перекрывает построение, а не наоборот.
 */
function Frame() {
  const lines: React.ReactElement[] = [];

  // Отметки проступей: короткие штрихи у дальнего края каждой плиты.
  // Они идут ЗА плитами и поднимаются вместе с ними — построение, из
  // которого вышла конструкция.
  for (let i = 0; i < N; i++) {
    const x = X0 + i * STEP_X + LEN + DX;
    const y = Y0 - i * STEP_Y + DY;
    lines.push(<line key={`t${i}`} x1={x + 8} y1={y} x2={x + 30} y2={y} />);
  }

  return (
    <g className="frame" strokeWidth="1" strokeLinecap="round">
      {lines}
    </g>
  );
}
