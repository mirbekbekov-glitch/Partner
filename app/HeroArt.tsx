'use client';

import { useEffect, useRef } from 'react';

/**
 * Фон героя: лестница заказчика и свет, идущий за курсором.
 *
 * Рисунок приходит готовым файлом, а не собирается кодом. Шесть попыток
 * нарисовать лестницу вектором — изометрия, профиль, столбики, консоли,
 * фигура в двух видах — показали границу: то, что рисуется координатами,
 * либо не читается лестницей, либо читается, но выглядит самодельным
 * рядом с настоящей типографикой. Картинку рисует художник, а не формулы.
 *
 * Из файла убраны знак в левом верхнем углу и адрес сайта в правом
 * нижнем: на первом экране они дублировали бы шапку и подвал, а знак
 * стоял бы прямо под настоящим знаком — это читается как ошибка вёрстки,
 * а не как подпись.
 *
 * Полотно рисунка почти белое, страница — тёплая кремовая. Поэтому он
 * наложен умножением: белое уходит в цвет фона, и рисунок оказывается НА
 * странице, а не вклеенным в неё прямоугольником.
 *
 * Тёмная версия — отдельный файл, собранный из того же рисунка. Две
 * прежние попытки провалились: сплошная инверсия переворачивает и
 * красный, тёмно-красная тень становится бледно-розовым светом и объём
 * читается наизнанку; выборочная, по насыщенности, оставляет мятные
 * пятна, потому что у почти белой бумаги насыщенность скачет.
 *
 * Верное деление проходит не по цвету, а по предмету: лист отдельно,
 * лестница отдельно. Маска объекта строится размыканием (тонкие линии
 * чертежа отсеиваются, лестница остаётся) и заливкой дыр, после чего
 * лист переворачивается по светлоте, а лестница остаётся как была.
 * Отсюда белые проступи и тёмная фигура в тёмной теме.
 *
 * Светлый файл лежит на странице умножением, тёмный — осветлением:
 * у первого лист белый, у второго чёрный, и каждый режим растворяет
 * свой лист в своём фоне.
 *
 * Рисунок чуть смещается за курсором — на несколько пикселей, в
 * противоход. Этого хватает, чтобы фон перестал быть наклейкой. На
 * телефоне указателя нет, при «меньше движения» смещение выключено.
 */
export function HeroArt() {
  const box = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = box.current;
    if (!el) return;
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    if (!window.matchMedia('(pointer: fine)').matches) return;

    let raf = 0;
    const onMove = (e: PointerEvent) => {
      if (raf) return;
      raf = requestAnimationFrame(() => {
        raf = 0;
        const r = el.getBoundingClientRect();
        const x = e.clientX - r.left;
        const y = e.clientY - r.top;
        el.style.setProperty('--mx', `${x}px`);
        el.style.setProperty('--my', `${y}px`);
        // Сдвиг в противоход курсору и в десять раз слабее: предмет
        // отзывается, но не убегает.
        el.style.setProperty('--px', `${(0.5 - x / r.width) * 18}px`);
        el.style.setProperty('--py', `${(0.5 - y / r.height) * 12}px`);
      });
    };
    const parent = el.parentElement ?? el;
    parent.addEventListener('pointermove', onMove);
    return () => {
      parent.removeEventListener('pointermove', onMove);
      if (raf) cancelAnimationFrame(raf);
    };
  }, []);

  return (
    <div className="hero-art" ref={box} aria-hidden="true">
      <div className="hero-glow" />
      {/* Обычный img, а не next/image: файл уже обрезан и сжат под своё
          место, одного размера достаточно, и оптимизатор здесь только
          добавил бы запрос. Размеры проставлены, чтобы место под рисунок
          занималось до загрузки и заголовок не прыгал.

          Два файла, как у знака в шапке: светлый и тёмный. Второй
          получен из первого — лист перевёрнут по светлоте, сама
          лестница оставлена как есть. Поэтому в тёмной теме у неё
          белые проступи и тёмная фигура, а не вывернутый наизнанку
          объём, которым кончились прежние попытки. */}
      <img src="/hero-stairs.webp" alt="" width={1024} height={892}
           className="on-light" decoding="async" fetchPriority="high" />
      <img src="/hero-stairs-dark.webp" alt="" width={1024} height={892}
           className="on-dark" decoding="async" />
    </div>
  );
}
