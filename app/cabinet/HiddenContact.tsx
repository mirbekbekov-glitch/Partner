/**
 * Контакт, закрытый инвариантом 4.
 *
 * Показывается явно, а не пустым местом: агент должен понимать, что контакт
 * существует и просто не положен ему, иначе он решит, что собственник не
 * заведён, и создаст дубликат — ровно то, что запрещает правило
 * «один человек — одна запись».
 */
export function ContactCell({ name }: { name: string | null }) {
  if (name) return <strong>{name}</strong>;
  return (
    <span className="hidden-contact" title="Контакт доступен агенту, который его привёл, участникам активной сделки и администратору">
      контакт скрыт
    </span>
  );
}
