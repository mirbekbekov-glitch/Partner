import { requireAdmin } from '@/lib/db/session';
import { Backfill } from './Backfill';

export const metadata = { title: 'Миниатюры' };
export const dynamic = 'force-dynamic';

export default async function PhotoThumbsPage() {
  // Страница админская, и проверка стоит здесь, а не только в маршруте:
  // иначе обычный агент увидел бы кнопку, которая ему ответит отказом.
  //
  // Отказ ПЕРЕХВАТЫВАЕТСЯ и показывается строкой — как на странице
  // агентов. Сперва я дал исключению улететь, и живая проверка показала
  // цену: агент, набравший адрес руками, получал «This page couldn't
  // load» с кодом 500. Это ложь дважды. Ничего не сломалось — ему просто
  // сюда нельзя; и выглядит это как авария сайта, а не как решение,
  // принятое нарочно.
  try {
    await requireAdmin();
  } catch (e) {
    return (
      <>
        <h1>Миниатюры</h1>
        <p className="error">{e instanceof Error ? e.message : 'Страница недоступна.'}</p>
      </>
    );
  }

  return (
    <>
      <h1>Миниатюры</h1>
      <p className="sub">Пересчёт для снимков, у которых миниатюры нет</p>

      <div className="card stack">
        <p>
          Миниатюра — уменьшенная копия снимка, её показывает список
          каталога. Без неё карточка тянет полный снимок: страница
          работает, но загружается заметно дольше, и так на каждой
          карточке.
        </p>
        <p className="key">
          Миниатюры нет у снимков, загруженных до появления сжатия, и у
          снимков из браузеров, которые уменьшать не умеют. Пересчёт
          делает эта страница: она скачивает снимок, уменьшает его здесь
          же и отправляет обратно. На сервере картинку пересобрать нечем.
        </p>
        <p className="key">
          Вкладку надо держать открытой. Прервётся — ничего не потеряется:
          готовые миниатюры уже сохранены, а повторный запуск возьмёт
          только оставшиеся.
        </p>

        <Backfill />
      </div>
    </>
  );
}
