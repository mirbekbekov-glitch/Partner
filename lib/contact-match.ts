/**
 * Похожи ли два имени настолько, чтобы предложить их объединить.
 *
 * Зачем отдельным модулем, а не запросом. Правило не выражается на SQL:
 *
 * 1. `lower()` в SQLite работает ТОЛЬКО с латиницей. `lower('ОРОЗОВ')`
 *    возвращает «ОРОЗОВ» — проверено запросом к боевой базе. То есть
 *    сравнение `lower(a.name) = lower(b.name)` для русских имён было
 *    РЕГИСТРОЗАВИСИМЫМ, и один и тот же человек, записанный капсом,
 *    дубликатом не считался. Это была не недоработка поиска, а неверное
 *    сравнение.
 * 2. «Орозов Нурлан» и «Орозов Н.» — одно и то же лицо, и такое правило
 *    на SQL не напишешь вовсе.
 *
 * Хранимая нормализованная колонка (как `phone_normalized` у телефонов)
 * закрыла бы только первый пункт, зато её пришлось бы поддерживать в
 * трёх местах — заведение, правка, объединение, — и однажды одно из них
 * отстало бы. Здесь одно правило в одном месте.
 *
 * Без 'server-only' намеренно: то же правило нужно форме в браузере,
 * чтобы предупредить до отправки. Обращений к базе здесь нет.
 */

/**
 * Имя → сопоставимый вид: нижний регистр средствами JS, края обрезаны,
 * пробелы схлопнуты, точки после инициалов убраны.
 *
 * toLowerCase() в JS, в отличие от SQLite, кириллицу приводит.
 */
export function nameKey(name: string | null | undefined): string {
  return (name ?? '')
    .toLowerCase()
    .replace(/[.]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Одно ли это лицо, судя по имени.
 *
 * Правило:
 * — полностью совпавшие имена — да, и это работает и для фирм («Этажи»);
 * — иначе: совпадает первое слово (фамилия), и каждое следующее слово
 *   одного является началом соответствующего слова другого. «Орозов
 *   Нурлан» и «Орозов Н.» — да; «Орозов Нурлан» и «Орозов Азамат» — нет.
 *
 * Одно слово против нескольких — НЕ совпадение. «Орозов» и «Орозов
 * Нурлан» объединять нельзя: однофамильцев больше, чем тёзок, и ложное
 * объединение здесь необратимо — присоединённая запись удаляется. Лучше
 * не предложить дубликат, чем склеить двух разных людей.
 */
export function looksLikeSameName(a: string, b: string): boolean {
  const left = nameKey(a);
  const right = nameKey(b);

  if (!left || !right) return false;
  if (left === right) return true;

  const one = left.split(' ');
  const two = right.split(' ');

  // Инициалы сравнивать можно только когда есть что сравнивать помимо
  // фамилии.
  if (one.length < 2 || two.length < 2) return false;
  if (one[0] !== two[0]) return false;

  const common = Math.min(one.length, two.length);
  for (let i = 1; i < common; i++) {
    const x = one[i]!;
    const y = two[i]!;
    if (!x.startsWith(y) && !y.startsWith(x)) return false;
  }

  return true;
}
