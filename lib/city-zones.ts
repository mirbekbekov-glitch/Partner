/**
 * Районы по городам — в том порядке, в каком их называет местный.
 *
 * Список нужен поиску: поле «Район» на пульте — выпадающий список, а не
 * строка ввода. Строкой человек пишет «Джал-23», «джал» и «Jal», и ни
 * одно из трёх не совпадает с тем, что агент ввёл в карточке. Список
 * такого разнобоя не допускает: в нём ровно те названия, которыми
 * пользуются в кабинете.
 *
 * Порядок — с севера на юг, строками, как город лежит на самом деле. Это
 * не прихоть: в алфавитном списке «Тунгуч» стоит рядом с «Центром», хотя
 * между ними полгорода, и выбрать соседний район становится нельзя — его
 * сначала надо вспомнить. Ценность порядка — в правде расположения,
 * поэтому город попадает сюда только с чьих-то слов, а не из базы.
 *
 * Города без списка не ломаются: у них в поле остаются районы, которые
 * встретились в самих объявлениях, — это названия, а не география, и
 * врать там нечему.
 */

const BISHKEK = [
  // Север
  'Ак-Орго', 'Арча-Бешик', 'Шлагбаум', 'Рабочий городок', 'Аламедин-1', 'Тунгуч',
  // Вдоль Чүй
  'Кызыл-Аскер', 'Филармония', 'Центр', 'Политех', 'Восток-5',
  // Юг
  'Маевка', 'Орто-Сай', 'Мадина', 'Юг-2', 'Кок-Жар',
  'Чон-Арык', 'Джал', 'Асанбай',
];

const ZONES: Record<string, string[]> = {
  Бишкек: BISHKEK,
};

/** Районы города — или пусто, если их никто не перечислял. */
export function zonesOf(city: string | null | undefined): string[] {
  return (city && ZONES[city]) || [];
}

/** Города, для которых районы перечислены руками. */
export function citiesWithZones(): string[] {
  return Object.keys(ZONES);
}
