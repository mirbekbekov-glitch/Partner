import 'server-only';
import { isDbError } from './errors';

/**
 * Отказ слоя доступа → фраза для агента.
 *
 * Раньше страницы показывали текст ошибки Postgres как есть, и это было
 * сознательно: в нём написано, какое правило не выполнено, и это полезнее
 * любой пересказанной формулировки. Правило остаётся, но теперь сообщения
 * пишем мы сами, и они уже человеческие — пересказывать нечего.
 *
 * Чужие ошибки наружу не идут. В тексте падения может оказаться что
 * угодно — путь файла, кусок запроса, идентификатор, — и показывать это
 * агенту незачем, а иногда и нельзя.
 */
export function explain(e: unknown): string {
  if (isDbError(e)) return e.message;

  console.error('необработанная ошибка слоя доступа', e);
  return 'Не получилось. Попробуйте ещё раз, а если повторится — скажите администратору.';
}

/** Удобная обёртка: выполнить и вернуть отказ строкой, а не исключением. */
export async function attempt(run: () => Promise<unknown>): Promise<string | null> {
  try {
    await run();
    return null;
  } catch (e) {
    return explain(e);
  }
}
