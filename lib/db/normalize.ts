/**
 * Приведение телефонов и названий к сопоставимому виду.
 *
 * Это перенос app.normalize_phone() и app.normalize_name() из Postgres, и
 * перенос дословный: правила менять нельзя, иначе уже записанные
 * нормализованные значения разойдутся с новыми и уникальность развалится.
 *
 * Модуль намеренно без 'server-only': те же правила нужны формам в браузере,
 * чтобы показать «такой номер уже есть» до отправки. Решает всё равно
 * сервер — здесь нет ни одного обращения к базе.
 */

/**
 * Телефон → сопоставимый вид.
 *
 * +996700111222, 0700 11 12 22 и 700111222 дают один результат. Иностранные
 * номера остаются цифрами как есть: их план нумерации мы не угадываем.
 *
 * Пустая строка на выходе означает «нормализовать нечего» — такие значения
 * в уникальный индекс не идут.
 */
export function normalizePhone(phone: string | null | undefined): string {
  const digits = (phone ?? '').replace(/\D/g, '');
  if (digits.length === 12 && digits.startsWith('996')) return digits.slice(-9);
  if (digits.length === 10 && digits.startsWith('0'))   return digits.slice(-9);
  return digits;
}

/**
 * Название → сопоставимый вид: нижний регистр, края обрезаны, пробелы внутри
 * схлопнуты. «Этажи», «этажи» и «ЭТАЖИ  » — одно агентство.
 */
export function normalizeName(name: string | null | undefined): string {
  return (name ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
}
