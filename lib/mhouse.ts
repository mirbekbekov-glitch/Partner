/**
 * Чем заполнять регион, если агент его не указал.
 *
 * Догадка ровно одна и ровно та же, что уже принята в схеме: объект без
 * города считается бишкекским. Для остальных городов догадываться нельзя —
 * населённых пунктов в справочнике площадки больше тысячи, и «Кант» из
 * Чуйской области неотличим от одноимённого в другой области без самого
 * справочника.
 */
export function regionOf(city: string, region: string | null): string | null {
  if (region) return region;
  return city.trim() === 'Бишкек' ? 'Чуйская область / Бишкек' : null;
}

/** Значение из списка — или ничего. Чужое значение площадка не примет. */
export function fromList(list: readonly string[], value: string | null): string | null {
  if (!value) return null;
  const found = list.find((v) => v.toLowerCase() === value.trim().toLowerCase());
  return found ?? null;
}
