/**
 * Срок в днях → слово справочника площадки.
 *
 * Направление то же, что у вида коммерции: главный — наш срок в днях,
 * слово площадки выводится. Иначе отбор «посуточно» пришлось бы делать
 * по чужому словарю, где «посуточно» и «по часам» различаются только
 * написанием.
 *
 * «По часам» мы не выводим: почасовая аренда — не наш товар, и
 * выдавать за неё суточную нельзя.
 */
export function mhouseTerm(min: number | null, max: number | null): string | null {
  if (min === null && max === null) return null;
  if (min !== null && min < 30) return 'посуточно';
  if (max === null || max > 180) return 'на долгий срок';
  return 'помесячно';
}

