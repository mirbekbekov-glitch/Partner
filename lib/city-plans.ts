const PLANS: Record<string, CityPlan> = {
  Бишкек: BISHKEK,
};

/**
 * Схема города — или ничего, если её никто не рисовал.
 *
 * Пусто здесь — обычное состояние, а не сбой: схем ровно столько, сколько
 * городов кто-то описал вручную.
 */
export function planFor(city: string | null | undefined): CityPlan | null {
  return (city && PLANS[city]) || null;
}

/** Города, для которых схема есть. */
export function citiesWithPlan(): string[] {
  return Object.keys(PLANS);
}
