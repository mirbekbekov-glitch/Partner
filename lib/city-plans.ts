/**
 * Схемы районов по городам.
 *
 * Это СХЕМЫ, а не карты, и названы они честно. Карта с метками требует
 * координат у каждого объекта, а их в базе нет: агент вводит адрес
 * словами. Рисовать метки «примерно» на настоящей карте нельзя — человек
 * поедет смотреть не туда.
 *
 * Схема делает ровно то, ради чего карту и открывают: показывает, где в
 * городе что есть, и даёт нажать на район. Вся её ценность — в ПРАВДЕ
 * расположения: местный должен узнать город с первого взгляда. Схема с
 * выдуманной раскладкой хуже, чем её отсутствие: отсутствие ничего не
 * обещает, а неверная раскладка обещает и обманывает.
 *
 * Отсюда правило: город попадает сюда, только когда раскладку назвал
 * человек, который этот город знает. Города без схемы не ломаются — у
 * них остаётся строка районов над каталогом, та же, что и у остальных:
 * это названия, а не география, и врать там нечему.
 *
 * Модуль отдельный от компонента: в компоненте раскладка была заперта
 * внутри разметки, и добавить второй город значило бы его переписать.
 */

/** Ячейка плана: название района и его место в сетке. */
export type Cell = { name: string; col: string; row: string };

export type CityPlan = {
  /** Главная ось города — по ней местный определяет стороны света. */
  avenue: string;
  /** Рисовать ли гряду гор по южному краю. */
  ridge: boolean;
  cells: Cell[];
};

