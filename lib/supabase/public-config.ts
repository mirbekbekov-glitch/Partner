import 'server-only';

/**
 * Публичные координаты Supabase, которые серверная страница передаёт
 * клиентским компонентам.
 *
 * Зачем это понадобилось. Раньше браузерный клиент читал
 * process.env.NEXT_PUBLIC_SUPABASE_URL прямо у себя. Значения с таким
 * префиксом подставляются в код во время сборки, и если сборке их не дали,
 * подставляется пустая строка — молча, без ошибки. Сборка проходит, а сайт
 * ломается: в браузере @supabase/ssr бросает «URL and Key are required».
 * Один раз это уже уронило прод целиком, потому что подстановка затронула и
 * серверный код, где до того значение честно читалось в рантайме.
 *
 * Теперь зависимость от сборки убрана. Значения читаются здесь, на сервере,
 * в рантайме — то есть из секретов Worker'а, где они и так лежат, — и
 * уезжают к клиентским компонентам пропсами. Пустая переменная при сборке
 * больше ничего не ломает, потому что сборка их вообще не видит.
 *
 * 'server-only' в первой строке — не украшение: если этот модуль случайно
 * импортируют из клиентского компонента, сборка упадёт с внятной ошибкой,
 * а не утащит серверное окружение в браузер.
 *
 * Анонимный ключ публичен по замыслу: доступ к данным ограничивает RLS, а не
 * секретность ключа. Поэтому отдавать его в разметке страницы безопасно —
 * ровно это и делал прежний вариант, просто через сборку.
 */
export type SupabasePublicConfig = { url: string; anonKey: string };

export function publicSupabaseConfig(): SupabasePublicConfig {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  // Падать здесь громко и сразу лучше, чем отдать клиенту пустые строки и
  // получить невнятную ошибку в чужом браузере.
  if (!url || !anonKey) {
    throw new Error(
      'Нет NEXT_PUBLIC_SUPABASE_URL или NEXT_PUBLIC_SUPABASE_ANON_KEY. ' +
      'Они задаются секретами Worker (npx cf secret put ИМЯ), сборке не нужны.',
    );
  }

  return { url, anonKey };
}
