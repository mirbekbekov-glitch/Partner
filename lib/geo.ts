/**
 * География: регион → город → район.
 *
 * Три уровня, а не два, по двум причинам. Первая: так устроен вопрос у
 * человека. Он выбирает не «Бишкек» из списка всех городов мира, а
 * сначала область, потом город, потом район — и список на каждом шаге
 * короткий. Вторая: площадка задумана шире Кыргызстана. Ташкент, Алматы
 * и Москва лягут сюда как ещё три региона, и ни одна страница от этого
 * не изменится — изменится только этот файл.
 *
 * Что здесь есть и чего нет. Здесь — названия, которыми пользуются
 * люди, и порядок, в котором их удобно искать. Здесь нет координат,
 * границ и почтовых индексов: карты у нас нет, и выдумывать под неё
 * данные не из чего.
 *
 * Районы перечислены пока только у Бишкека, и это честное состояние, а
 * не недоделка: список районов города должен назвать тот, кто город
 * знает. У города без списка район вводится словами — поле остаётся, и
 * то, что агент написал в карточке, попадёт в список само (см. страницу
 * каталога: названия из объявлений подмешиваются к словарным).
 */

export type City = {
  name: string;
  /** Районы — в том порядке, в каком их ищут, а не по алфавиту. */
  zones?: string[];
};

export type Region = {
  name: string;
  /** Страна нужна, когда регионов станет больше одной страны. */
  country: string;
  cities: City[];
};

