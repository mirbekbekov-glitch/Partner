/** Названия регионов — для списка на пульте. */
export function regions(): string[] {
  return GEO.map((r) => r.name);
}

/** Города региона, а без региона — все города словаря. */
export function citiesOf(region: string | null | undefined): string[] {
  const list = region ? GEO.filter((r) => r.name === region) : GEO;
  return list.flatMap((r) => r.cities.map((c) => c.name));
}

/** Районы города — или пусто, если их никто не перечислял. */
export function zonesOf(city: string | null | undefined): string[] {
  if (!city) return [];
  for (const r of GEO) {
    for (const c of r.cities) if (c.name === city) return c.zones ?? [];
  }
  return [];
}

/** Регион, в котором лежит город, — чтобы по городу выставить регион. */
export function regionOf(city: string | null | undefined): string | null {
  if (!city) return null;
  for (const r of GEO) {
    if (r.cities.some((c) => c.name === city)) return r.name;
  }
  return null;
}

/**
 * Приведение названия к виду, по которому ищут.
 *
 * «6 мкр», «6 м-н», «6 микрорайон» и «6мкр» — одно и то же место, и
 * человек вправе набрать любое из них. Регистр, «ё», дефисы и пробелы
 * тоже не должны мешать: «кокжар» обязан находить «Кок-Жар».
 */
export function zoneKey(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/микрорайон|мкрн|мкр|м-н|мн\b/g, 'мкр')
    .replace(/[\s\-–—.,]/g, '');
}

/** Подходит ли район под набранное. */
export function zoneMatch(zone: string, query: string): boolean {
  const q = zoneKey(query);
  return q === '' || zoneKey(zone).includes(q);
}
