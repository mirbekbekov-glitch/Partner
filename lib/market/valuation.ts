/**
 * Оценка по сопоставимым: счёт, и только счёт.
 *
 * ЗДЕСЬ НЕТ МОДЕЛИ И НЕ БУДЕТ. Цену считает арифметика по объявлениям,
 * которые лежат в базе, а модель — если её вообще звать — может потом
 * пересказать готовый результат словами. Наоборот нельзя: число,
 * названное моделью, невозможно проверить и не на чем защитить перед
 * собственником. Агент приходит к человеку и говорит «ваша квартира
 * стоит столько, вот двадцать похожих» — вот это разговор.
 *
 * МЕДИАНА, А НЕ СРЕДНЕЕ. Это не вкусовщина: в индексе лежит настоящее
 * объявление «комната 20 м² за 2 002 810 $» — так написал продавец, и
 * курс там сходится, то есть разбор не ошибся. Одна такая строка сдвинет
 * среднее по восемнадцати комнатам в разы. Медиану она не сдвигает
 * вовсе — на то медиана и нужна.
 *
 * ЦЕНА СЧИТАЕТСЯ ЗА МЕТР, а не целиком. Квартиры в выборке разной
 * площади, и складывать их цены — складывать разное. За метр они
 * сравнимы, а итог получается умножением на площадь оцениваемого.
 */

/** Сколько минорных единиц в основной. То же, что в lib/db/money.ts. */
const MINOR = 100;

/** Одно сопоставимое: ровно то, что нужно счёту. */
export type Comparable = {
  id: string;
  url: string;
  /** Цена в минорных единицах, уже приведённая к одной валюте. */
  priceMinor: number;
  area: number;
  rooms: number | null;
  address: string | null;
  sellerKind: 'owner' | 'agency' | 'unknown';
  /** Когда объявление в последний раз поднимали — для свежести выборки. */
  bumpedAt: string | null;
};

/** На чём построена оценка: это показывается агенту, а не прячется. */
export type Basis = {
  /** Сколько объявлений вошло в счёт. */
  count: number;
  /** Насколько пришлось расширить выборку, чтобы их набрать. */
  widening: Widening;
  /** Границы площади, попавшие в выборку. */
  areaFrom: number;
  areaTo: number;
};

/** Как подбирались сопоставимые. Порядок — от точного к широкому. */
export type Widening =
  | 'точно'          // тот же район, те же комнаты, близкая площадь
  | 'без района'     // район пришлось снять
  | 'комнаты ±1'     // комнатность расширена на соседнюю
  | 'без комнат'     // комнатность снята совсем
  | 'широко';        // снято и то, и другое

/** Итог оценки. */
export type Valuation = {
  /** Вилка и середина — в минорных единицах той же валюты. */
  lowMinor: number;
  midMinor: number;
  highMinor: number;
  /** Цена за метр, по которой всё и считалось. */
  perMetreMinor: number;
  basis: Basis;
  /** Объявления, на которых построен вывод. Показываются агенту целиком. */
  used: Comparable[];
};

/**
 * Сколько объявлений нужно, чтобы вообще считать.
 *
 * Пять — не круглое число для красоты. На четырёх медиана это среднее
 * двух средних значений, и одно кривое объявление двигает её заметно. На
 * трёх «медиана» — просто среднее из трёх. Меньше пяти оценка выдаётся
 * не вилкой, а отказом: «мало похожих» — это честный ответ, а оценка по
 * двум объявлениям честным ответом не является.
 */
export const MIN_COMPARABLES = 5;

/** Насколько площадь сопоставимого может отличаться от оцениваемого. */
export const AREA_SPREAD = 0.25;

/** Значение квантиля в отсортированном ряду, линейной интерполяцией. */
export function quantile(sorted: number[], q: number): number {
  if (sorted.length === 0) return 0;
  if (sorted.length === 1) return sorted[0];

  const pos = (sorted.length - 1) * q;
  const low = Math.floor(pos);
  const high = Math.ceil(pos);
  if (low === high) return sorted[low];
  return sorted[low] + (sorted[high] - sorted[low]) * (pos - low);
}

/** Медиана. */
export function median(values: number[]): number {
  return quantile([...values].sort((a, b) => a - b), 0.5);
}

/**
 * Оценка по готовой выборке сопоставимых.
 *
 * Вилка — это НЕ «плюс-минус сколько-то процентов». Это четверть и три
 * четверти самого рынка: половина похожих объявлений стоит внутри неё.
 * Такую вилку можно показать собственнику и объяснить, откуда она, а
 * «±10%» объяснить нечем.
 */
export function valuate(
  comparables: Comparable[],
  area: number,
  widening: Widening,
): Valuation | null {
  if (comparables.length < MIN_COMPARABLES || area <= 0) return null;

  const perMetre = comparables
    .filter((c) => c.area > 0)
    .map((c) => c.priceMinor / c.area)
    .sort((a, b) => a - b);

  if (perMetre.length < MIN_COMPARABLES) return null;

  const low = quantile(perMetre, 0.25);
  const mid = quantile(perMetre, 0.5);
  const high = quantile(perMetre, 0.75);

  const areas = comparables.map((c) => c.area).sort((a, b) => a - b);

  // Округление до целой единицы валюты, а не до копейки. Оценка «85 739
  // долларов 69 центов» обещает точность, которой у неё нет: это медиана
  // по полутора десяткам чужих объявлений, и центы в ней — шум, который
  // читается как уверенность.
  const whole = (value: number) => Math.round(value / MINOR) * MINOR;

  return {
    lowMinor: whole(low * area),
    midMinor: whole(mid * area),
    highMinor: whole(high * area),
    perMetreMinor: whole(mid),
    basis: {
      count: comparables.length,
      widening,
      areaFrom: areas[0],
      areaTo: areas[areas.length - 1],
    },
    used: comparables,
  };
}

/**
 * Насколько цена отличается от рынка, в процентах.
 *
 * Положительное — дороже рынка. Считается от середины выборки: именно её
 * мы и называем рынком.
 */
export function awayFromMarket(priceMinor: number, valuation: Valuation): number {
  if (valuation.midMinor <= 0) return 0;
  return Math.round(((priceMinor - valuation.midMinor) / valuation.midMinor) * 100);
}

/**
 * Курс, посчитанный ПО САМИМ ОБЪЯВЛЕНИЯМ.
 *
 * Зачем он нужен. Продажа на площадке идёт в долларах и сомах сразу, а
 * аренда комнат — только в сомах. Чтобы сравнивать их между собой, нужен
 * курс, и брать его неоткуда: ключей к курсовым службам у нас нет, а
 * вписать число в код — значит получить молча устаревающую цифру.
 *
 * Зато в индексе лежат тысячи объявлений, где площадка назвала ОБЕ
 * валюты. Их отношение и есть сегодняшний курс рынка — не выдуманный, не
 * вчерашний, а тот, по которому прямо сейчас торгуются.
 *
 * Медиана, а не среднее, по той же причине: одно объявление с опечаткой
 * в цене не должно двигать курс.
 */
export function rateFromPairs(pairs: Array<{ usdMinor: number; kgsMinor: number }>): number | null {
  const rates = pairs
    .filter((p) => p.usdMinor > 0 && p.kgsMinor > 0)
    .map((p) => p.kgsMinor / p.usdMinor)
    .filter((r) => r >= 60 && r <= 130);

  // Меньше десятка пар — это не курс, а случайность. Лучше отказаться
  // пересчитывать, чем пересчитать по кривому числу: ошибка в курсе
  // перекосит всю оценку целиком и незаметно.
  if (rates.length < 10) return null;
  return median(rates);
}
