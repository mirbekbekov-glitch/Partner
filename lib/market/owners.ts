/**
 * Поиск собственников: кому из них есть смысл звонить.
 *
 * ЗАЧЕМ. Объявление от хозяина, которое висит давно и дешевеет, — это не
 * «лид», а человек, который устал продавать сам. Ему нужен агент, и он
 * это уже понял. Остальные собственники в выдаче — те, кто подал вчера и
 * полон надежд; звонок им сейчас только раздражает.
 *
 * ПРИЗНАКИ, А НЕ БАЛЛ ИЗ НИОТКУДА. Каждый множитель ниже назван и виден
 * агенту словами на странице. Это прямо скопировано у LeoHubs, и
 * справедливо: открытая методика превращает чёрный ящик в довод, который
 * агент может повторить вслух.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Телефона. Площадка прячет его намеренно и открывает по
 * нажатию; собирать его в обход этого решения мы не станем — это чужие
 * личные данные, а не наша добыча. В списке стоит ссылка, агент
 * открывает и нажимает «показать», как сделал бы любой человек.
 */

/** Строка индекса, из которой считается готовность. */
export type OwnerRow = {
  id: string;
  url: string;
  address: string | null;
  rooms: number | null;
  area: number | null;
  priceUsd: number | null;
  priceKgs: number | null;
  /** Когда объявление подано. Берётся со страницы объявления. */
  postedAt: string | null;
  /** Когда объявление впервые попалось НАШЕМУ обходу. */
  firstSeenAt: string;
  bumped: boolean;
  /** Сколько раз цена менялась вниз и на сколько процентов всего. */
  drops: number;
  dropPercent: number;
};

/** Один названный признак готовности. */
export type Signal = { text: string; weight: number };

export type OwnerLead = {
  row: OwnerRow;
  /** Сумма весов: ею список и сортируется. */
  score: number;
  signals: Signal[];
  /** Сколько дней объявление на площадке, и откуда это известно. */
  days: number | null;
  daysFrom: 'публикация' | 'наш обход';
};

/** Сколько дней прошло. */
function daysSince(at: string | null, nowMs: number): number | null {
  if (!at) return null;
  const ms = nowMs - Date.parse(at);
  return Number.isFinite(ms) ? Math.max(0, Math.floor(ms / (24 * 3600_000))) : null;
}

/**
 * Готовность продавца к разговору.
 *
 * Веса подобраны по смыслу, а не по науке, и названы здесь открыто:
 *
 * - СНИЖЕНИЕ ЦЕНЫ — сильнейший признак. Человек уже уступил, то есть
 *   признал, что по прежней цене не продаётся. Вес растёт с размером
 *   уступки, но ограничен: уступка в 40% чаще означает, что объявление
 *   начиналось с фантазии, а не что продавец сговорчив.
 * - ВИСИТ ДАВНО — второй по силе. Месяц это норма рынка, три месяца —
 *   уже усталость, полгода — почти наверняка готов слушать.
 * - ПОДНИМАЮТ ОБЪЯВЛЕНИЕ — продавец ещё старается, то есть объект не
 *   продан и не заброшен. Без этого признака давний срок означает скорее
 *   брошенное объявление, по которому не дозвониться.
 */
export function rank(rows: OwnerRow[], nowMs: number): OwnerLead[] {
  const leads: OwnerLead[] = rows.map((row) => {
    const signals: Signal[] = [];

    const postedDays = daysSince(row.postedAt, nowMs);
    const seenDays = daysSince(row.firstSeenAt, nowMs);
    const days = postedDays ?? seenDays;
    const daysFrom: OwnerLead['daysFrom'] = postedDays === null ? 'наш обход' : 'публикация';

    if (row.drops > 0 && row.dropPercent > 0) {
      const weight = Math.min(row.dropPercent, 20) / 2;
      signals.push({
        text: row.drops === 1
          ? `цена снижена на ${row.dropPercent}%`
          : `цена снижалась ${row.drops} раза, всего на ${row.dropPercent}%`,
        weight,
      });
    }

    if (days !== null) {
      if (days >= 180) signals.push({ text: `висит больше полугода (${days} дн.)`, weight: 10 });
      else if (days >= 90) signals.push({ text: `висит больше трёх месяцев (${days} дн.)`, weight: 7 });
      else if (days >= 30) signals.push({ text: `висит больше месяца (${days} дн.)`, weight: 3 });
    }

    if (row.bumped) signals.push({ text: 'объявление поднимают — продавец ещё старается', weight: 2 });

    return {
      row,
      score: signals.reduce((sum, s) => sum + s.weight, 0),
      signals,
      days,
      daysFrom,
    };
  });

  // Без единого признака звонить не за чем: это обычное свежее
  // объявление, и его хозяин ничего ещё не решил.
  return leads
    .filter((l) => l.signals.length > 0)
    .sort((a, b) => b.score - a.score);
}

/**
 * Черновик первого сообщения собственнику.
 *
 * СОБИРАЕТСЯ ИЗ ФАКТОВ, А НЕ МОДЕЛЬЮ. Это письмо незнакомому человеку от
 * имени агентства, и выдуманная в нём деталь — «вижу, вы давно
 * продаёте» про объявление недельной давности — стоит сделки и
 * репутации. Поэтому в тексте стоит ровно то, что мы знаем: адрес,
 * площадь, срок и снижение цены, если оно было.
 *
 * Черновик, а не отправка: агент читает, правит и пишет сам. Рассылки
 * здесь нет и быть не должно.
 */
export function invitation(lead: OwnerLead, agencyName: string, agentName: string): string {
  const r = lead.row;
  const what = [
    r.rooms ? `${r.rooms}-комн.` : null,
    r.area ? `${r.area} м²` : null,
    r.address,
  ].filter(Boolean).join(', ');

  const lines = [
    'Здравствуйте!',
    '',
    `Меня зовут ${agentName}, я из агентства ${agencyName}.`,
    // Без глаголов в прошедшем времени от первого лица: «увидел»
    // навязало бы агенту мужской род, а половина агентов — женщины.
    `Пишу по вашему объявлению: ${what || 'объект на house.kg'}.`,
  ];

  if (lead.days !== null && lead.days >= 30) {
    lines.push(
      `Судя по площадке, оно размещено ${lead.days} дн. назад${
        r.drops > 0 ? `, и цену вы уже снижали` : ''
      }.`,
    );
  } else if (r.drops > 0) {
    lines.push('Цену вы уже снижали.');
  }

  lines.push(
    '',
    'Если продаёте сами и это затянулось — могу показать, за сколько',
    'похожие объекты действительно уходят в вашем районе, и что в',
    'объявлении мешает звонкам. Это бесплатно и ни к чему вас не',
    'обязывает.',
    '',
    'Если решите работать с агентством — расскажу условия отдельно.',
    '',
    agentName,
  );

  return lines.join('\n');
}
