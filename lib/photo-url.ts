/**
 * Адреса снимков: полный и миниатюра.
 *
 * Правило одно и держится тем, что загрузка кладёт оба файла:
 * у снимка `…/abc.jpg` миниатюра лежит в `…/abc.jpg@thumb.webp`.
 *
 * Суффикс ДОПИСЫВАЕТСЯ, а не подменяет расширение. Сперва я делал подмену
 * (`abc.jpg` → `abc@thumb.webp`) — и правило перестало быть обратимым:
 * по имени миниатюры уже не узнать, был исходник `.jpg` или `.png`. А
 * обратный путь нужен: маршрут отдачи по адресу миниатюры ищет полный
 * снимок, когда миниатюры нет.
 *
 * Выводить адрес по правилу, а не хранить его вторым полем, — сознательно.
 * Второе поле пришлось бы заполнять, переносить при правке и помнить о нём
 * в каждом месте, где снимки читаются; при этом оно ничего бы не добавило:
 * миниатюра либо есть, либо её нет, и это видно по самому файлу.
 *
 * Для чужих ссылок миниатюры нет и быть не может — отдаётся сам снимок.
 * Для снимков, загруженных до появления миниатюр, маршрут отдачи сам
 * подставит полный файл.
 *
 * Модуль без 'server-only': адреса нужны и странице, и браузеру.
 */

/** Наш ли это снимок. Чужие ссылки правилу не подчиняются. */
export function isOwnPhoto(url: string): boolean {
  return /^\/photos\/objects\/[0-9a-f-]+\/[0-9a-f-]+\.[a-z]+$/i.test(url);
}

/** Миниатюра снимка — или он сам, если миниатюры быть не может. */
export function thumbOf(url: string): string {
  if (!isOwnPhoto(url)) return url;
  return `${url}@thumb.webp`;
}

/** Ключ миниатюры по ключу полного снимка. */
export function thumbKey(key: string): string {
  return `${key}@thumb.webp`;
}

/** Полный снимок по ключу миниатюры. Нужен маршруту отдачи для запасного пути. */
export function fullKeyOf(thumb: string): string | null {
  return thumb.endsWith('@thumb.webp') ? thumb.slice(0, -'@thumb.webp'.length) : null;
}
