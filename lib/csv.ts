/**
 * Выгрузка списков в CSV.
 *
 * Разделитель — точка с запятой, в начале файла метка порядка байтов.
 * Excel в русской локали читает запятую как десятичный знак, и файл с
 * запятыми открывается одной колонкой; без метки он же принимает UTF-8 за
 * однобайтовую кодировку, и кириллица превращается в кракозябры. Оба
 * решения — ради того, чтобы файл открылся двойным щелчком, а не через
 * мастер импорта.
 */

/** Метка порядка байтов: без неё Excel не распознаёт UTF-8. */
const BOM = '﻿';

/**
 * Ячейка таблицы, обезвреженная для Excel.
 *
 * Значение, начинающееся с =, +, - или @, Excel и LibreOffice считают
 * формулой: строка «=1+1» из заметки агента превратится в двойку, а
 * «=HYPERLINK(...)» — в ссылку, по которой кто-то щёлкнет. Поэтому перед
 * таким значением ставится апостроф: он не виден в ячейке и делает её
 * текстом. Это защита файла, а не данных: в самой базе значение остаётся
 * как есть.
 */
function cell(value: unknown): string {
  if (value === null || value === undefined) return '';

  let text = String(value);
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;

  // Кавычки удваиваются, и в кавычки берётся всё, где есть разделитель,
  // кавычка или перенос строки.
  if (/[";\n\r]/.test(text)) text = `"${text.replace(/"/g, '""')}"`;
  return text;
}

/** Таблица в CSV: первая строка — заголовки колонок. */
export function toCsv(headers: string[], rows: unknown[][]): string {
  const lines = [headers.map(cell).join(';')];
  for (const row of rows) lines.push(row.map(cell).join(';'));
  // CRLF: того же ждут Excel и описание формата (RFC 4180).
  return BOM + lines.join('\r\n') + '\r\n';
}

/**
 * Ответ с файлом.
 *
 * Имя файла — только латиница и цифры: в заголовке Content-Disposition
 * кириллица требует отдельного кодирования, и часть клиентов его путает.
 * Дата в имени нужна, чтобы выгрузки не перезаписывали друг друга в папке
 * загрузок.
 */
export function csvResponse(name: string, csv: string): Response {
  const day = new Date().toISOString().slice(0, 10);

  return new Response(csv, {
    headers: {
      'content-type': 'text/csv; charset=utf-8',
      'content-disposition': `attachment; filename="${name}-${day}.csv"`,
      // Выгрузка — срез на сейчас, и кешировать его нельзя: второй щелчок
      // должен дать свежие строки, а не вчерашние.
      'cache-control': 'no-store',
    },
  });
}
