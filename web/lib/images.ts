/**
 * Перекодирование изображений.
 *
 * Зачем вообще слой: перекодирование — это не оптимизация, а защита. Файл,
 * попавший в хранилище, создан нами; присланные байты не записываются никогда
 * (инвариант 11). Отсюда три требования к любой реализации, и они важнее
 * того, какая библиотека внутри:
 *
 *   1. байты РАСКОДИРОВАТЬ и ЗАКОДИРОВАТЬ заново — иначе не-изображение,
 *      переименованное в .jpg, проходит насквозь;
 *   2. метаданные ВЫБРОСИТЬ — в снимке квартиры EXIF содержит координаты
 *      съёмки, то есть адрес собственника;
 *   3. снимок «боком» РАЗВЕРНУТЬ по EXIF до того, как EXIF выброшен.
 *
 * Почему две реализации. sharp — нативный модуль, в workerd он не грузится
 * вовсе; привязка Images живёт только в воркере. То есть выбор определяется
 * рантаймом, а не вкусом, и настройкой он быть не должен: переменная
 * окружения здесь означала бы лишь возможность выставить единственное
 * неверное значение. Поэтому рантайм определяется, а не спрашивается.
 */

/** Готовые байты и то, что о них нужно знать базе. */
export type Encoded = {
  bytes: Uint8Array;
  width: number;
  height: number;
};

/**
 * Что сделать с картинкой.
 *
 * Описание в терминах задачи, а не библиотеки: «вписать» и «квадрат» — это
 * решения продукта (снимок объекта не обрезаем, аватар обрезаем), и обе
 * реализации обязаны понимать их одинаково.
 */
export type Shape =
  /** Вписать в квадрат со стороной `side`, НЕ увеличивая маленькое. */
  | { kind: "fit"; side: number; quality: number }
  /** Квадрат `side`×`side` с обрезкой по содержательной части кадра. */
  | { kind: "square"; side: number; quality: number };

/**
 * В воркере нет sharp, в node нет привязки Images. Признак взят из рантайма:
 * workerd сообщает о себе через `navigator.userAgent`.
 */
function onWorkers(): boolean {
  return (
    typeof navigator !== "undefined" &&
    navigator.userAgent === "Cloudflare-Workers"
  );
}

/**
 * Имя реализации. Нужно проверкам и журналу: «перекодировано» без указания
 * чем — бесполезная запись, когда реализаций две.
 */
export function encoderName(): string {
  return onWorkers() ? "images-binding" : "sharp";
}

/**
 * Перекодировать.
 *
 * Импорт реализации отложенный, и это не стиль: статический `import sharp`
 * ломал весь кабинет в воркере — модуль вычисляется при загрузке, а нативный
 * файл там не находится. Отложенный импорт до своей ветки не доходит, поэтому
 * sharp в воркере не вычисляется никогда.
 *
 * Ошибка всегда одна и та же для человека: битый файл, документ с
 * расширением .jpg и попытка подсунуть исполняемое — это один случай
 * «кодировщик не смог», и разница между ними пользователю ничего не даёт.
 */
export async function encode(input: Uint8Array, shape: Shape): Promise<Encoded> {
  const impl = onWorkers()
    ? (await import("./images.cf.ts")).encode
    : (await import("./images.sharp.ts")).encode;
  return impl(input, shape);
}
