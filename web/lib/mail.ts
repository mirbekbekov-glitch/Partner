/**
 * Отправка письма.
 *
 * Один шов на всю почту: коды входа сейчас, уведомления о показах потом.
 * Провайдера ещё нет, и это нормально — выбрать его дешевле, чем WhatsApp, но
 * это всё равно решение владельца продукта: домен, обратный адрес, деньги.
 *
 * ЧТО НУЖНО ОТ ПРОВАЙДЕРА, чтобы письмо с кодом доходило, а не падало в спам:
 *
 *   — свой домен и записи SPF и DKIM в его DNS. Без них письмо с адреса вроде
 *     noreply@partner.kg уходит в спам у половины получателей, и человек
 *     решит, что система сломана;
 *   — обратный адрес, который кто-то читает. Письмо с кодом входа иногда
 *     получает тот, кто входа не запрашивал, и ему надо куда-то написать;
 *   — отправка через API или SMTP с паролем приложения — не через личный
 *     почтовый ящик сотрудника.
 *
 * SMTP выбран как общий знаменатель: он есть у любого провайдера, включая
 * почту на собственном домене и Google Workspace. Если провайдер окажется
 * с HTTP API (Resend, Postmark, SendGrid), здесь добавится ветка, и больше
 * ничего менять не придётся.
 *
 * Зависимости для отправки пока нет нарочно: ставить почтовую библиотеку до
 * того, как выбран провайдер, значит выбрать его молча.
 */

export type Letter = {
  to: string;
  subject: string;
  text: string;
};

export function mailFrom(): string {
  return process.env.MAIL_FROM ?? "";
}

export async function sendMail(letter: Letter): Promise<void> {
  const host = process.env.SMTP_HOST;
  const from = mailFrom();

  if (!host || !from) {
    throw new Error(
      "Почта не настроена: нужны SMTP_HOST и MAIL_FROM. Смотрите web/.env.example и web/lib/mail.ts — там написано, что требуется от провайдера.",
    );
  }

  throw new Error(
    `Почтовый клиент не установлен. Провайдер не выбран, поэтому библиотека отправки не добавлена в зависимости — иначе выбор был бы сделан молча. Письмо для ${letter.to} не отправлено.`,
  );
}
