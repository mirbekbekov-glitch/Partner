/**
 * Отправка кода входа.
 *
 * Канал входа — почта (инвариант 6, третья редакция). Она бесплатна,
 * заводится за час и ни от кого не зависит.
 *
 * WhatsApp подключается строкой `OTP_TRANSPORT=whatsapp` и настройками
 * поставщика — код отправки в lib/whatsapp.ts готов. Чего он не заменяет:
 * проверки бизнеса в Meta, платёжного способа и утверждённого шаблона
 * категории «аутентификация». Это не код, это кабинет Meta и деньги, и
 * решение остаётся за владельцем продукта: каждое сообщение с кодом платное.
 *
 * Отправка вынесена сюда за одну функцию. До выбора почтового провайдера
 * работает `dev`: код печатается в журнал сервера и показывается на странице
 * входа. Так кабинет можно разрабатывать и показывать целиком, не делая вид,
 * что почта уже подключена, и не пряча заглушку в середине обработчика формы.
 *
 * Подключение настоящего провайдера — это строка `OTP_TRANSPORT=email` в
 * окружении. Ни база, ни экраны не меняются.
 *
 * Значение называется `email`, а не `smtp`, и это не косметика: отправка идёт
 * через HTTP API провайдера, потому что исходящего SMTP в воркере нет вовсе.
 * Звать такой вызов «smtp» значило бы соврать в имени настройки — а потом
 * кто-то стал бы искать, почему не работает порт 587.
 */

export type OtpTransport = "dev" | "email" | "whatsapp";

/** Канал, которым код уходит. Совпадает с `login_channel` в базе. */
export type LoginChannel = "email" | "whatsapp";

export function transport(): OtpTransport {
  const value = process.env.OTP_TRANSPORT;
  // Значения по умолчанию здесь НЕТ, и это главное в этой функции.
  //
  // Раньше по умолчанию был `dev`, то есть самый опасный из вариантов: он
  // показывает код входа прямо на странице. Значит выкладывание, в котором
  // просто ЗАБЫЛИ настроить почту, открывало кабинет любому желающему —
  // введи чужой адрес и прочитай код. Забывчивость не должна приводить к
  // открытой двери, поэтому без явно заданного значения вход не работает
  // вовсе.
  if (!value) {
    throw new Error(
      "OTP_TRANSPORT не задан: вход не настроен. Смотрите web/.env.example — " +
        "значения dev, email, whatsapp. Значения по умолчанию нет намеренно: " +
        "dev показывает код на экране, и забытая настройка открыла бы кабинет.",
    );
  }
  if (value !== "dev" && value !== "email" && value !== "whatsapp") {
    throw new Error(`OTP_TRANSPORT должен быть dev, email или whatsapp, получено: ${value}`);
  }

  // WhatsApp ОТПРАВЛЯТЬ умеет, а ВПУСКАТЬ — ещё нет, и дверь закрыта здесь.
  //
  // Отправка написана и проверена (lib/whatsapp.ts, npm run smoke:whatsapp).
  // Не хватает другого конца: по инварианту 6 ключ личности — адрес почты,
  // `agents.email` обязателен и проверяется на вид «имя@домен». Телефон им
  // быть не может.
  //
  // Без этой проверки включение канала выглядело бы работающим и кончалось
  // худшим из возможных: человек вводит телефон, МЫ ПЛАТИМ за сообщение с
  // кодом, он вводит верный код — и получает «во входе нет подтверждённого
  // адреса почты». Ошибка про почту тому, кто ввёл телефон.
  //
  // Что для этого нужно решить — в docs/market/platform-spec.md, раздел 7,
  // пункт 1: либо телефон становится вторым ключом личности (и тогда один
  // человек может завести два аккаунта), либо WhatsApp остаётся каналом
  // входа для аккаунта, заведённого почтой.
  if (value === "whatsapp") {
    throw new Error(
      "OTP_TRANSPORT=whatsapp: отправка готова, но вход по телефону не достроен. " +
        "Ключ личности по инварианту 6 — адрес почты, и телефон им пока быть не может: " +
        "человек получил бы платное сообщение и уткнулся в ошибку про почту. " +
        "Решение в docs/market/platform-spec.md, раздел 7, пункт 1.",
    );
  }

  return value;
}

/** Каким каналом отправлять код. Из канала следует, что спрашивать у человека. */
export function channel(): LoginChannel {
  return transport() === "whatsapp" ? "whatsapp" : "email";
}

/**
 * Показывать ли код на странице.
 *
 * Правило одно: канал `dev` показывает код, потому что в этом весь его смысл —
 * ничего не отправляется, и достать код больше неоткуда.
 *
 * Раньше здесь стояла ещё проверка NODE_ENV, и она делала ровно обратное
 * задуманному. В бою она убирала с экрана и код, и предупреждение «режим
 * разработки» — то есть гасила единственный громкий признак неверной
 * настройки ровно тогда, когда он нужен, и превращала небезопасную
 * конфигурацию в молча неработающий вход.
 *
 * Теперь признак на месте: страница входа с каналом `dev` сама сообщает, что
 * она не для боя, и сообщает это в любой сборке.
 */
export function showsCodeOnScreen(): boolean {
  return transport() === "dev";
}

export async function sendLoginCode(address: string, code: string): Promise<void> {
  switch (transport()) {
    case "dev":
      // Намеренно и в журнал, а не только в ответ: так виден путь, которым
      // код пойдёт в бою, и видно, что сервер действительно его отправляет.
      console.info(`[вход] код для ${address}: ${code}`);
      return;

    case "email": {
      const { sendMail } = await import("./mail");
      await sendMail({
        to: address,
        subject: `Код входа: ${code}`,
        text:
          `Код входа в кабинет: ${code}\n\n` +
          `Код действует 5 минут и работает один раз.\n` +
          `Если вы не запрашивали вход, просто не отвечайте на это письмо — ` +
          `без кода в кабинет никто не войдёт.\n`,
      });
      return;
    }

    case "whatsapp": {
      const { sendWhatsAppCode } = await import("./whatsapp");
      await sendWhatsAppCode({ to: address, code });
      return;
    }
  }
}
