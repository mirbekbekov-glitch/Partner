"use client";

/**
 * Кнопка «Сохранить PDF».
 *
 * Клиентская ровно потому, что `window.print()` бывает только в браузере.
 * Больше здесь ничего нет и быть не должно: вся вёрстка листа живёт в
 * обычных стилях под `@media print`, то есть PDF — это та же страница, а не
 * её второй вариант.
 *
 * Название на кнопке — «Сохранить PDF», а не «Печать», потому что в жизни её
 * нажимают ради файла, который уйдёт клиенту в мессенджер, а не ради бумаги.
 * В диалоге браузера «Сохранить как PDF» и так первый пункт.
 */
export function PrintBar() {
  return (
    <p className="print-bar">
      <button type="button" className="btn" onClick={() => window.print()}>
        Сохранить PDF
      </button>
    </p>
  );
}
