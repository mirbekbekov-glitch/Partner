import { bindings, defineConfig, defineWorker } from "cf/config";

/**
 * Воркер Liberterra.
 *
 * Все значения объявлены через `bindings.secret()`, то есть приходят извне:
 * местно — из `.dev.vars`, в продакшне — из секретов воркера. В репозиторий не
 * попадает ни одно значение, но попадает их СПИСОК, и это главное: воркер,
 * которому не хватает переменной, ругается при запуске, а не отдаёт
 * наполовину работающий сайт. Раньше такой список существовал только в
 * `.env.example`, то есть на честном слове.
 */
export default defineConfig({
  worker: defineWorker({
    name: "liberterra",
    entrypoint: "vinext/server/fetch-handler",
    compatibilityDate: "2026-11-22",
    // pg, node:crypto (подписи сессий) и node:stream (отдача байтов) —
    // без этого флага воркер не соберётся.
    compatibilityFlags: ["nodejs_compat"],

    // РАЗМЕЩЕНИЕ ВОРКЕРА РЯДОМ С БАЗОЙ, а не рядом с посетителем.
    //
    // Против интуиции, и это измерено: одна загрузка главной делает 8
    // обращений к базе, и `pg` их не конвейеризирует — каждое это обход сети.
    // Воркер у края сети в Бишкеке платит восемь обходов до региона базы;
    // воркер, прижатый к региону базы, платит один обход от посетителя и
    // восемь местных.
    //
    // Регион здесь обязан совпадать с регионом базы. Сейчас база в
    // ap-northeast-1 (Токио) на AWS. Если база переедет, эту строку надо
    // поменять вместе с ней — иначе воркер окажется прижат к пустому месту и
    // станет хуже, чем без размещения вовсе.
    placement: { mode: "targeted", region: "aws:ap-northeast-1" },
    assets: {
      htmlHandling: "none",
      notFoundHandling: "none",
      runWorkerFirst: ["/*", "!/_next/static/*", "!/*/_next/static/*"],
    },
    env: {
      ASSETS: bindings.assets(),

      // Перекодирование картинок. Заменяет sharp, который в workerd не
      // грузится: нативный модуль.
      IMAGES: bindings.images(),

      // Привязка R2 закомментирована намеренно: R2 на аккаунте не включён, а
      // привязка к несуществующему бакету сорвала бы выкладывание. Байты
      // лежат в Supabase Storage через драйвер s3 — см. PHOTO_S3_* ниже.
      //
      // Когда R2 включат, вернуть эту строку, создать бакет и поменять
      // PHOTO_STORAGE на r2. Драйвер готов и проверен на местном бакете.
      // Бакет обязан остаться ЗАКРЫТЫМ: публичный доступ обошёл бы проверку
      // права в базе (инвариант 11).
      //
      // R2: bindings.r2({ name: "liberterra-photos" }),

      // Пул соединений к базе на стороне Cloudflare. Привязка закомментирована
      // потому, что `id` — это идентификатор конфигурации Hyperdrive на
      // аккаунте: его создают из строки подключения Supabase (именно Direct
      // connection, не пулер), и подставить его может только владелец
      // аккаунта. Пока привязки нет, воркер берёт DATABASE_URL и ходит в базу
      // напрямую — работает, но без пула у края сети.
      //
      // КОНФИГУРАЦИЮ СОЗДАВАТЬ ТОЛЬКО С --caching-disabled. Это не настройка
      // производительности, а условие правильности. Hyperdrive кэширует
      // ответы на читающие запросы (по умолчанию ВКЛЮЧЕНО, max_age 60 с), и
      // ключ кэша — текст запроса с параметрами. Ни роль, ни клеймы входа в
      // ключ не входят.
      //
      // У нас один и тот же текст запроса под разными ролями возвращает
      // РАЗНЫЕ строки: фильтрует RLS. Значит кэш отдал бы выборку одного
      // агента другому — ровно то, против чего построен весь продукт. Наши
      // запросы к тому же идут к представлениям, внутри которых auth.uid() и
      // now(), а Hyperdrive ищет такие функции сопоставлением ТЕКСТА запроса
      // — в тексте `select … from listing_terms_v` их не видно, поэтому
      // защита «запросы со STABLE-функциями не кэшируются» здесь не работает.
      //
      // HYPERDRIVE: bindings.hyperdrive({
      //   id: "<идентификатор конфигурации Hyperdrive, созданной с --caching-disabled>",
      //   dev: { connectionString: "postgresql://postgres:local@127.0.0.1:55432/partner" },
      // }),

      // База. Роли — не украшение, а защита: каждая страница ходит в базу под
      // понижённой ролью, и RLS отдаёт только то, что этой роли позволено.
      DATABASE_URL: bindings.secret(),
      CATALOG_DB_ROLE: bindings.secret(),
      AUTH_DB_ROLE: bindings.secret(),
      CABINET_DB_ROLE: bindings.secret(),
      NOTIFY_DB_ROLE: bindings.secret(),

      // Подпись кук входа.
      SESSION_SECRET: bindings.secret(),

      // Ссылки в отчётах собственнику уходят наружу, поэтому адрес сайта
      // задаётся, а не угадывается из запроса.
      SITE_URL: bindings.secret(),

      // Доставка кодов входа и уведомлений. ВНИМАНИЕ: `dev` показывает код
      // прямо на странице входа — в публичном вебе это открытая дверь.
      OTP_TRANSPORT: bindings.secret(),
      NOTIFY_TRANSPORT: bindings.secret(),

      // Почта. Провайдер с HTTP API: исходящего SMTP в воркере нет.
      MAIL_PROVIDER: bindings.secret(),
      MAIL_FROM: bindings.secret(),
      MAIL_API_KEY: bindings.secret(),

      // Хранилище фотографий. PHOTO_DIR здесь нет намеренно: драйвер диска
      // в воркере не работает и работать не должен, поэтому требовать от
      // воркера переменную, которая ему никогда не понадобится, — значит
      // держать в списке обязательного то, что ни на что не влияет.
      PHOTO_STORAGE: bindings.secret(),

      // Для PHOTO_STORAGE=s3. Supabase Storage живёт в том же проекте, что
      // база: `https://<ref>.supabase.co/storage/v1/s3`, регион проекта.
      // Ключи создаются в панели Supabase (Storage → S3 Access Keys) и
      // кладутся в секреты воркера.
      PHOTO_S3_BUCKET: bindings.secret(),
      PHOTO_S3_ENDPOINT: bindings.secret(),
      PHOTO_S3_REGION: bindings.secret(),
      PHOTO_S3_ACCESS_KEY_ID: bindings.secret(),
      PHOTO_S3_SECRET_ACCESS_KEY: bindings.secret(),
    },
  }),
});
